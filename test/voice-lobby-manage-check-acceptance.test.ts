// Voice lobby Manage Server check acceptance (dashboard parity spec, section 4.1
// as applied by slice 1b). Pins the live per-write Discord permission check:
// a guild-behavior write is allowed only when the writer holds Manage Server
// (or Administrator, or owns the guild) at write time. Every outage,
// rejection and malformed answer fails closed to false. Permission bitfields
// are Discord stringified integers past 32 bits, so the computation must use
// BigInt, never 32-bit operators.
//
