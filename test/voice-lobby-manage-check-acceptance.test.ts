import { describe, expect, it, vi } from "vitest";
import {
  ADMINISTRATOR_BIT,
  hasManageServer,
  MANAGE_GUILD_BIT,
} from "../src/admin/voice-lobby-guard";

const GUILD_ID = "326474832151838730";
const USER_ID = "100000000000000111";
const MANAGE_ROLE_ID = "222000000000000222";
const BOT_TOKEN = "fixture-bot-token-voice-lobby";

const DISCORD_API = "https://discord.com/api/v10";
const ROLES_URL = `${DISCORD_API}/guilds/${GUILD_ID}/roles`;
const MEMBER_URL = `${DISCORD_API}/guilds/${GUILD_ID}/members/${USER_ID}`;
const GUILD_URL = `${DISCORD_API}/guilds/${GUILD_ID}`;

type CheckOpts = {
  guildId?: string;
  userId?: string;
  botToken?: string;
};

function optsFor(overrides: CheckOpts = {}) {
  return {
    guildId: GUILD_ID,
    userId: USER_ID,
    botToken: BOT_TOKEN,
    ...overrides,
  };
}

function jsonResponse(status: number, body: unknown): Response {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json" },
  });
}

/** Canned Discord answers keyed by exact URL, with a hit log and header log. */
function discordStub(routes: Record<string, Response | Error>): {
  fetchFn: typeof fetch;
  hits: string[];
  authHeaders: string[];
} {
  const hits: string[] = [];
  const authHeaders: string[] = [];
  const fetchFn = vi.fn(async (input: string | URL | Request, init?: RequestInit) => {
    const url = typeof input === "string" ? input : input.toString();
    hits.push(url);
    const headers = (init?.headers ?? {}) as Record<string, string>;
    authHeaders.push(headers["authorization"] ?? headers["Authorization"] ?? "");
    const next = routes[url];
    if (next === undefined) throw new Error(`unexpected Discord URL: ${url}`);
    if (next instanceof Error) throw next;
    return next;
  });
  return { fetchFn: fetchFn as unknown as typeof fetch, hits, authHeaders };
}

const rolesWith = (permissions: string, id: string = MANAGE_ROLE_ID): unknown[] => [
  { id: GUILD_ID, name: "@everyone", permissions: "0" },
  { id, name: "Mods", permissions },
];

const memberWith = (roles: string[]): unknown => ({ roles });

const guildOwnedBy = (ownerId: string): unknown => ({ id: GUILD_ID, owner_id: ownerId });

describe("voice lobby Manage Server bits", () => {
  it("exports the Discord Manage Guild and Administrator bits", () => {
    expect(Number(MANAGE_GUILD_BIT)).toBe(0x20);
    expect(Number(ADMINISTRATOR_BIT)).toBe(0x8);
  });
});

describe("voice lobby Manage Server verdicts", () => {
  it("allows a member whose role carries Manage Server", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("32")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
  });

  it("allows an Administrator without the Manage bit", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("8")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
  });

  it("allows through the @everyone role's bits", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, [{ id: GUILD_ID, name: "@everyone", permissions: "32" }]),
      [MEMBER_URL]: jsonResponse(200, memberWith([])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
  });

  it("unions every held role instead of reading one", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, [
        { id: GUILD_ID, name: "@everyone", permissions: "0" },
        { id: "333000000000000333", name: "Plain", permissions: "1" },
        { id: MANAGE_ROLE_ID, name: "Mods", permissions: "32" },
      ]),
      [MEMBER_URL]: jsonResponse(200, memberWith(["333000000000000333", MANAGE_ROLE_ID])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
  });

  it("refuses a member whose roles lack both bits", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("refuses a member with no roles and plain @everyone", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith([])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("ignores a stale membership that names an unknown role", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith(["444000000000000444"])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("allows the guild owner without a manage role", async () => {
    const { fetchFn, hits } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith([])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy(USER_ID)),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
    expect(hits).toContain(GUILD_URL);
  });

  it("skips the guild read once the roles already allow", async () => {
    const { fetchFn, hits } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("32")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
    expect(hits).not.toContain(GUILD_URL);
  });

  it("computes past 32 bits: a high bit alone does not allow", async () => {
    const { fetchFn } = discordStub({
      // 2^41: bit 41 set, Manage (bit 5) and Administrator (bit 3) clear.
      [ROLES_URL]: jsonResponse(200, rolesWith("2199023255552")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("computes past 32 bits: Manage beside a high bit allows", async () => {
    const { fetchFn } = discordStub({
      // 2^41 + 0x20: a 32-bit `|` would drop the high half and misread this.
      [ROLES_URL]: jsonResponse(200, rolesWith("2199023255584")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(true);
  });
});

describe("voice lobby Manage Server fail-closed behavior", () => {
  it.each([
    ["roles 500", { rolesStatus: 500 }],
    ["roles 429", { rolesStatus: 429 }],
    ["member 404", { memberStatus: 404 }],
    ["member 500", { memberStatus: 500 }],
  ])("refuses when Discord answers %s", async (_label, statuses) => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(
        (statuses as { rolesStatus?: number }).rolesStatus ?? 200,
        rolesWith("32"),
      ),
      [MEMBER_URL]: jsonResponse(
        (statuses as { memberStatus?: number }).memberStatus ?? 200,
        memberWith([MANAGE_ROLE_ID]),
      ),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("refuses when the transport throws, even for a manager", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: new TypeError("network down"),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("refuses on non-JSON answers instead of crashing", async () => {
    const html = new Response("not json", {
      status: 200,
      headers: { "content-type": "text/html" },
    });
    const { fetchFn } = discordStub({ [ROLES_URL]: html, [MEMBER_URL]: html });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("refuses when the guild read fails after negative roles", async () => {
    const { fetchFn } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
      [GUILD_URL]: jsonResponse(500, { message: "down" }),
    });
    await expect(hasManageServer({ ...optsFor(), fetchFn })).resolves.toBe(false);
  });

  it("refuses with zero fetches on a blank bot token", async () => {
    const { fetchFn } = discordStub({});
    const fn = vi.mocked(fetchFn);
    await expect(hasManageServer({ ...optsFor({ botToken: "   " }), fetchFn })).resolves.toBe(
      false,
    );
    expect(fn).not.toHaveBeenCalled();
  });

  it.each(["not-an-id", "", "12 34", "0x20"])(
    "emits zero fetches on a malformed guild id %s",
    async (guildId) => {
      const { fetchFn } = discordStub({});
      const fn = vi.mocked(fetchFn);
      await expect(hasManageServer({ ...optsFor({ guildId }), fetchFn })).resolves.toBe(false);
      expect(fn).not.toHaveBeenCalled();
    },
  );

  it.each(["not-an-id", "", "12 34"])(
    "emits zero fetches on a malformed user id %s",
    async (userId) => {
      const { fetchFn } = discordStub({});
      const fn = vi.mocked(fetchFn);
      await expect(hasManageServer({ ...optsFor({ userId }), fetchFn })).resolves.toBe(false);
      expect(fn).not.toHaveBeenCalled();
    },
  );
});

describe("voice lobby Manage Server wire shape", () => {
  it("calls the three Discord reads with the bot token", async () => {
    const { fetchFn, hits, authHeaders } = discordStub({
      [ROLES_URL]: jsonResponse(200, rolesWith("1")),
      [MEMBER_URL]: jsonResponse(200, memberWith([MANAGE_ROLE_ID])),
      [GUILD_URL]: jsonResponse(200, guildOwnedBy("999999999999999999")),
    });
    await hasManageServer({ ...optsFor(), fetchFn });
    expect(hits).toContain(ROLES_URL);
    expect(hits).toContain(MEMBER_URL);
    expect(hits).toContain(GUILD_URL);
    for (const header of authHeaders) {
      expect(header).toBe(`Bot ${BOT_TOKEN}`);
    }
  });
});
