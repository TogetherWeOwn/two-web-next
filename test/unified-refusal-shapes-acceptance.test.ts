describe("one JSON 422 shape", () => {
  it("logged 422s share error plus fields plus request_id with error invalid", async () => {
    const responses = [await rsvp422(true), await event422(true), await profile422(true)];
    const bodies: Record<string, unknown>[] = [];
    for (const res of responses) {
      expect(res.status).toBe(422);
      expect(res.headers.get("content-type")).toContain("application/json");
      const body = (await res.json()) as Record<string, unknown>;
      expect(Object.keys(body).sort()).toEqual(["error", "fields", "request_id"]);
      expect(body.error).toBe("invalid");
      expect(typeof body.fields).toBe("object");
      expect(body.request_id).toBe(RAY);
      bodies.push(body);
    }
    const shapes = bodies.map((body) => Object.keys(body).sort().join(","));
    expect(new Set(shapes).size).toBe(1);
  });

  it("bare 422s share error plus fields without request_id", async () => {
    const responses = [await rsvp422(false), await event422(false), await profile422(false)];
    for (const res of responses) {
      expect(res.status).toBe(422);
      const body = (await res.json()) as Record<string, unknown>;
      expect(Object.keys(body).sort()).toEqual(["error", "fields"]);
      expect(body.error).toBe("invalid");
      expect("request_id" in body).toBe(false);
    }
  });
});

describe("one JSON 405/415 shape", () => {
  it("logged JSON 405/415 share one envelope with request_id", async () => {
    const responses = [
      await rsvp405(true),
      await profile405(true),
      await profile415(true),
      await event415(true),
    ];
    const keySets: string[] = [];
    for (const res of responses) {
      expect([405, 415]).toContain(res.status);
      expect(res.headers.get("content-type") ?? "").toContain("application/json");
      const body = (await res.json()) as Record<string, unknown>;
      expect(typeof body.error).toBe("string");
      expect(body.request_id).toBe(res.headers.get("x-request-id"));
      expect(body.request_id).toBe(RAY);
      keySets.push(Object.keys(body).sort().join(","));
    }
    expect(new Set(keySets).size).toBe(1);
  });

  it("bare JSON 405/415 share one envelope without request_id", async () => {
    const responses = [
      await rsvp405(false),
      await profile405(false),
      await profile415(false),
      await event415(false),
    ];
    const keySets: string[] = [];
    for (const res of responses) {
      expect([405, 415]).toContain(res.status);
      expect(res.headers.get("content-type") ?? "").toContain("application/json");
      const body = (await res.json()) as Record<string, unknown>;
      expect(typeof body.error).toBe("string");
      expect("request_id" in body).toBe(false);
      keySets.push(Object.keys(body).sort().join(","));
    }
    expect(new Set(keySets).size).toBe(1);
  });

  it("405s share one error value and 415s share one error value", async () => {
    const errorOf = async (res: Response): Promise<unknown> => {
      expect(res.headers.get("content-type") ?? "").toContain("application/json");
      return ((await res.json()) as { error?: unknown }).error;
    };
    const rsvp = await errorOf(await rsvp405(true));
    const post = await errorOf(await profile405(true));
    const patch = await errorOf(await profile415(true));
    const event = await errorOf(await event415(true));
    expect(typeof rsvp).toBe("string");
    expect(typeof patch).toBe("string");
    expect(rsvp).toBe(post);
    expect(patch).toBe(event);
  });
});

describe("browser negotiation parity", () => {
  it("profile PATCH 415 renders HTML for browsers (control)", async () => {
    const { client, cookie } = await profileClient(true);
    const res = await client.request(
      `/members/${OWNER_ID}`,
      {
        method: "PATCH",
        headers: {
          cookie,
          origin: APP_URL,
          "content-type": "text/plain",
          accept: "text/html",
          "cf-ray": RAY,
        },
        body: "not a save body",
      },
      profileEnv,
    );
    expect(res.status).toBe(415);
    expect(res.headers.get("content-type")).toContain("text/html");
    expect(await res.text()).toContain('class="recovery-code" aria-hidden="true">415<');
  });

  it("profile PATCH 415 keeps text for text/plain callers (control)", async () => {
    const { client, cookie } = await profileClient(true);
    const res = await client.request(
      `/members/${OWNER_ID}`,
      {
        method: "PATCH",
        headers: {
          cookie,
          origin: APP_URL,
          "content-type": "text/plain",
          accept: "text/plain",
          "cf-ray": RAY,
        },
        body: "not a save body",
      },
      profileEnv,
    );
    expect(res.status).toBe(415);
    expect(res.headers.get("content-type")).toContain("text/plain");
    expect(await res.text()).toBe("Unsupported Media Type");
  });

  it("profile POST 405 keeps text for browsers (control)", async () => {
    const { client, cookie } = await profileClient(true);
    const res = await client.request(
      `/members/${OWNER_ID}`,
      {
        method: "POST",
        headers: {
          cookie,
          origin: APP_URL,
          "content-type": "application/json",
          accept: "text/html",
          "cf-ray": RAY,
        },
        body: JSON.stringify({}),
      },
      profileEnv,
    );
    expect(res.status).toBe(405);
    expect(res.headers.get("Allow")).toBe("GET, PATCH, POST");
    expect(await res.text()).toBe("Method Not Allowed");
  });

  it("RSVP 405 keeps an empty body with Allow for browsers (control)", async () => {
    const res = await loggedMount((app) => registerRsvpRoutes(app, async () => member)).request(
      `/events/${ULID_KEY}/rsvp`,
      { method: "POST", headers: { accept: "text/html", "cf-ray": RAY } },
      rsvpEnv,
    );
    expect(res.status).toBe(405);
    expect(res.headers.get("Allow")).toBe("PUT, DELETE");
    expect(await res.text()).toBe("");
  });

  it("event 415 stays JSON-only for browsers (control)", async () => {
    const res = await loggedMount((app) => registerWriteRoutes(app, async () => moderator)).request(
      "/events",
      {
        method: "POST",
        headers: { "content-type": "text/plain", accept: "text/html", "cf-ray": RAY },
        body: "not an event body",
      },
      eventEnv,
    );
    expect(res.status).toBe(415);
    expect(res.headers.get("content-type")).toContain("application/json");
  });

  it("405s keep their Allow headers (control)", async () => {
    const rsvp = await rsvp405(true);
    expect(rsvp.status).toBe(405);
    expect(rsvp.headers.get("Allow")).toBe("PUT, DELETE");
    const profile = await profile405(true);
    expect(profile.status).toBe(405);
    expect(profile.headers.get("Allow")).toBe("GET, PATCH, POST");
  });
});
