type BotCall = {
  action: string;
  body: Record<string, string>;
  headers: Record<string, string>;
};

const DISCORD_API = "https://discord.com/api/v10";
const rolesUrl = (guildId: string = GUILD_ID): string => `${DISCORD_API}/guilds/${guildId}/roles`;
const memberUrl = (guildId: string = GUILD_ID, userId: string = USER_ID): string =>
  `${DISCORD_API}/guilds/${guildId}/members/${userId}`;
const guildUrl = (guildId: string = GUILD_ID): string => `${DISCORD_API}/guilds/${guildId}`;

const manageRolesPayload = (): unknown[] => [
  { id: GUILD_ID, name: "@everyone", permissions: "0" },
  { id: MANAGE_ROLE_ID, name: "Mods", permissions: "32" },
];

const plainRolesPayload = (): unknown[] => [
  { id: GUILD_ID, name: "@everyone", permissions: "0" },
  { id: MANAGE_ROLE_ID, name: "Members", permissions: "1" },
];

/**
 * Route the global fetch the page's two egresses use: the signed bot client
 * (per-request `createBotClient` with the default transport) and the live
 * Discord Manage check (discordFetch with the default transport). Anything
 * else is an unexpected network call and fails loudly.
 */
function installStubs(scenario: {
  bot?: Response[];
  roles?: unknown[];
  rolesStatus?: number;
  member?: unknown;
  memberStatus?: number;
  memberRoles?: string[];
  guildOwnerId?: string;
  guildStatus?: number;
  discordThrow?: boolean;
}): { botCalls: BotCall[]; discordHits: string[] } {
  const botCalls: BotCall[] = [];
  const discordHits: string[] = [];
  const botQueue = [...(scenario.bot ?? [])];
  const rolesPayload = scenario.roles ?? manageRolesPayload();
  const memberPayload = scenario.member ?? { roles: scenario.memberRoles ?? [MANAGE_ROLE_ID] };
  const guildPayload = { id: GUILD_ID, owner_id: scenario.guildOwnerId ?? "999999999999999999" };

  const stub = async (input: string | URL | Request, init?: RequestInit): Promise<Response> => {
    const url =
      typeof input === "string" ? input : input instanceof URL ? input.toString() : input.url;
    if (url.startsWith(`${BOT_URL}/internal/actions`)) {
      const raw = typeof init?.body === "string" ? init.body : "";
      const body = JSON.parse(raw) as Record<string, string>;
      botCalls.push({
        action: body["action"] ?? "",
        body,
        headers: { ...((init?.headers ?? {}) as Record<string, string>) },
      });
      const next = botQueue.shift();
      if (!next) throw new Error(`unexpected bot call #${botCalls.length}: ${body["action"]}`);
      return next;
    }
    if (url.startsWith(`${DISCORD_API}/`)) {
      discordHits.push(url);
      if (scenario.discordThrow) throw new TypeError("network down");
      if (url === rolesUrl()) return jsonResponse(scenario.rolesStatus ?? 200, rolesPayload);
      if (url === memberUrl()) return jsonResponse(scenario.memberStatus ?? 200, memberPayload);
      if (url === guildUrl()) return jsonResponse(scenario.guildStatus ?? 200, guildPayload);
      throw new Error(`unexpected Discord URL: ${url}`);
    }
    throw new Error(`unexpected fetch: ${url}`);
  };
  vi.stubGlobal("fetch", stub as unknown as typeof fetch);
  return { botCalls, discordHits };
}

