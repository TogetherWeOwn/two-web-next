function unescapeHtml(value: string): string {
  const entities: Record<string, string> = {
    amp: "&",
    lt: "<",
    gt: ">",
    quot: '"',
    "#39": "'",
    "#x27": "'",
  };
  return value.replace(
    /&(amp|lt|gt|quot|#39|#x27);/g,
    (match, name: string) => entities[name] ?? match,
  );
}

function cardBlock(html: string, key: string): string {
  const anchor = html.indexOf(`data-event-key="${key}"`);
  expect(anchor, `card for ${key} is rendered`).toBeGreaterThan(-1);
  return html.slice(html.lastIndexOf("<li", anchor), html.indexOf("</li>", anchor));
}

function hostInner(card: string): string | null {
  const match = new RegExp(`<p\\b[^>]*data-testid="${HOST_TESTID}"[^>]*>([\\s\\S]*?)</p>`).exec(
    card,
  );
  return match ? (match[1] ?? "") : null;
}

function scheduleInfoBlock(card: string): string | null {
  const match = /<div\b[^>]*class="schedule-info"[^>]*>([\s\S]*?)<\/div>/.exec(card);
  return match ? (match[0] ?? null) : null;
}

const stripTags = (html: string): string =>
  html
    .replace(/<[^>]*>/g, " ")
    .replace(/\s+/g, " ")
    .trim();

