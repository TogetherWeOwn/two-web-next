// Minimal schedule fixture: upcoming + past + month-grid routing by SQL shape,
// distinct-games answered empty (all fixtures are game-less unless set), RSVP
// aggregates return zero counts. No game filtering needed here.
function scheduleFixture(args: {
  upcoming?: EventRow[];
  monthRows?: EventRow[];
  past?: EventRow[];
  source?: DiscordEventsSource;
}) {
  const upcoming = args.upcoming ?? [];
  const monthRows = args.monthRows ?? [];
  const past = args.past ?? [];
  const source = args.source ?? discordSource();
  const queries: { sql: string; params: unknown[] }[] = [];
  const columns = Object.keys(getTableColumns(events)) as (keyof EventRow)[];
  const encode = (row: EventRow) =>
    columns.map((k) => {
      const v = row[k];
      return v instanceof Date ? v.toISOString() : v;
    });
  const db = drizzle(async (sql, params) => {
    queries.push({ sql, params: [...params] });
    if (sql.includes('from "rsvps"')) return { rows: [] };
    if (sql.startsWith('select "discord_event_id" from "events"')) return { rows: [] };
    if (/select\s+distinct/i.test(sql) && /game/i.test(sql)) return { rows: [] };
    if (sql.includes('"starts_at" < $')) {
      return { rows: monthRows.map(encode) };
    }
    // Past drawer: ends_at upper bound (`<`); upcoming uses `>=` and never matches.
    if (/"ends_at" </.test(sql)) {
      if (/^select count/i.test(sql)) return { rows: [[past.length]] };
      return { rows: past.map(encode) };
    }
    let rows = upcoming;
    // Public schedule excludes drafts via `status != 'draft'`; mirror it so the
    // draft-exclusion CONTROL proves the route predicate, not an empty fixture.
    if (sql.includes("!= 'draft'")) rows = rows.filter((row) => row.status !== "draft");
    if (/"event_key" = \$/.test(sql)) {
      rows = rows.filter((row) => params.includes(row.eventKey));
    }
    if (/^select count/i.test(sql)) return { rows: [[rows.length]] };
    if (sql.includes("limit")) {
      const hasOffset = sql.includes(" offset ");
      const offset = hasOffset ? Number(params.at(-1)) : 0;
      const limit = Number(params.at(hasOffset ? -2 : -1));
      const start = Number.isSafeInteger(offset) && offset > 0 ? offset : 0;
      const end = Number.isSafeInteger(limit) ? start + limit : rows.length;
      rows = rows.slice(start, end);
    }
    return { rows: rows.map(encode) };
  });
  Object.assign(db, {
    transaction: async (fn: (tx: Db) => Promise<void>) =>
      fn({ execute: async () => {} } as unknown as Db),
  });
  const adminDb = db as unknown as Db;
  const env = { ...baseEnv, ADMIN_DB: adminDb, DISCORD_EVENTS: source } as unknown as Env;
  return {
    db: adminDb,
    env,
    queries,
    source,
    request: (path: string, init?: RequestInit) => app.request(path, init, env),
  };
}

