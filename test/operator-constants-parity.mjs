// Operator-constants parity: one source of truth for staging origin, QA IDs,
// probe key.
//
// Run: node --test test/operator-constants-parity.mjs (offline; no DB, no
// network). The F6 build wires this file into the `test:smoke` script so
// `npm run check` names the canonical file on drift.
//
// Contract (failing-first; every parity message names the canonical file):
// - `ci/operator-constants.mjs` exports STAGING_ORIGIN, APEX_ORIGIN,
//   WWW_ORIGIN, QA_MEMBER_DISCORD_ID, QA_MODERATOR_DISCORD_ID, byte-identical
//   to the pins below, with no imports of its own.
// - Every bin/ci runtime copy below imports the canonical module instead of
//   carrying a literal. Existing export names stay (alias the canonical
//   value); no behavior change.
// - Fail-closed guards (e2e/staging-guard.mjs, e2e/watch-guard.mjs, the seed
//   validator, src/qa.ts) keep local literals; the parity tests fail on drift.
// - The smoke probe value is exported as SMOKE_PROBE_KEY from bin/smoke.mjs
//   and imported by test/smoke.test.mjs with no literal copies left.
// - QA snowflakes: bin/seed-staging.mjs imports them; the census workflow and
//   e2e fixtures either import them or keep byte-identical literals.
//
// Deliberately out of scope (pins, not copies): unit-test fixtures under
// test/**, Playwright spec origin literals, workflow origin literals,
// docs/** prose, spike/** notes, selftest-only literals that stay byte-equal,
// and src/probes/internal-action-drill.ts (owned by another slice).
//
// Owned by the operator-constants acceptance card; corrections return there.
// Do not edit this file in the build.

