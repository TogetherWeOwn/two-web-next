const ROOT = join(dirname(fileURLToPath(import.meta.url)), "..");
const CANONICAL_FILE = "ci/operator-constants.mjs";
const CANONICAL_SPEC = "../ci/operator-constants.mjs";

// Byte-identical pins of the production literals. The build changes no value.
const PIN_STAGING_ORIGIN = "https://next.togetherweown.com";
const PIN_APEX_ORIGIN = "https://togetherweown.com";
const PIN_WWW_ORIGIN = "https://www.togetherweown.com";
const PIN_QA_MEMBER_ID = "900000000000001396";
const PIN_QA_MODERATOR_ID = "900000000000001397";
const PIN_PROBE_VALUE = "00000000000000000000000001";

const read = (rel) => readFileSync(join(ROOT, rel), "utf8");
const countOccurrences = (haystack, needle) => haystack.split(needle).length - 1;
const escapeRegExp = (text) => text.replace(/[.*+?^${}()|[\]\\]/g, "\\$&");

let canonicalPromise = null;
function canonical() {
  canonicalPromise ??= import(CANONICAL_SPEC).catch((error) => {
    throw new assert.AssertionError({
      message:
        `operator-constants single source of truth: missing ${CANONICAL_FILE} ` +
        `(${error.message}); the build creates it exporting STAGING_ORIGIN, APEX_ORIGIN, ` +
        `WWW_ORIGIN, QA_MEMBER_DISCORD_ID, QA_MODERATOR_DISCORD_ID`,
    });
  });
  return canonicalPromise;
}

function canonicalSource() {
  try {
    return read(CANONICAL_FILE);
  } catch (error) {
    assert.fail(
      `operator-constants single source of truth: missing ${CANONICAL_FILE} ` +
        `(${error.message}); the build creates it first`,
    );
  }
}

let qaPromise = null;
function qaModule() {
  qaPromise ??= build({
    entryPoints: [join(ROOT, "src/qa.ts")],
    bundle: true,
    write: false,
    format: "esm",
    platform: "node",
  }).then(
    async (bundle) =>
      await import(
        `data:text/javascript;base64,${Buffer.from(bundle.outputFiles[0].text).toString("base64")}`
      ),
  );
  return qaPromise;
}

