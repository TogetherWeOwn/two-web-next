// Voice config bot-client acceptance (dashboard parity spec, section 7 slice
// 1b over the paired bot slice's verbs). Pins `voice.config.get` and
// `voice.config.set` on the existing signed internal-action client
// (`createBotClient`): wire encoding, pre-send validation, success parsing and
// failure passthrough. The route branches on the failure *code*
// (`version_conflict` re-reads); the client never maps it away.
//
// Expected RED: every test below fails with "client.getVoiceConfig is not a
// function" (or setVoiceConfig) — the verbs do not exist yet. The Builder adds
// them to `src/bot/client-factory.ts` with result types in
// `src/bot/client-types.ts` and input validation in `src/bot/client-validation.ts`.
// Builder: implement the verbs. Do not edit this file.

import { describe, expect, it, vi } from "vitest";
import { createBotClient } from "../src/bot/client";
import { BotTerminalError, BotTransportError } from "../src/jobs/types";

const GUILD_ID = "326474832151838730";
const UUID = "1e9d2f1a-2b3c-4d5e-8f90-123456789abc";

const OPTS = {
  url: "https://bot-staging.internal.example",
  secret: "s",
  keyId: "web-staging",
};

type VoiceConfigClient = {
  getVoiceConfig(guildId: string): Promise<
    | {
        ok: true;
        requestId: string | null;
        settings: Record<string, unknown>;
        version: number;
        updatedBy: string | null;
        updatedAt: string | null;
      }
    | { ok: false; code: string; status: number; retryable: boolean }
  >;
  setVoiceConfig(
    guildId: string,
    settings: Record<string, unknown>,
    expectedVersion: number,
    idempotencyKey: string,
  ): Promise<
    | { ok: true; requestId: string | null; version: number; replayed: boolean }
    | { ok: false; code: string; status: number; retryable: boolean }
  >;
};

const asVoice = (client: unknown): VoiceConfigClient => client as VoiceConfigClient;

function jsonResponse(status: number, body: unknown, headers: Record<string, string> = {}) {
  return new Response(JSON.stringify(body), {
    status,
    headers: { "content-type": "application/json", ...headers },
  });
}

function clientWith(responses: Response[]) {
  const seen: { url: string; init: RequestInit }[] = [];
  const fetchFn = vi.fn(async (url: string, init: RequestInit) => {
    seen.push({ url, init });
    const next = responses.shift();
    if (!next) throw new Error("no more stubbed responses");
    return next;
  });
  return {
    client: asVoice(createBotClient({ ...OPTS, fetchFn: fetchFn as unknown as typeof fetch })),
    seen,
    fetchFn,
  };
}

const SETTINGS = {
  text_channels: "private",
  position: "below_lobby",
  group: "123456789012345678",
  inherit_permissions: true,
  default_limit: 12,
  always_private: false,
  access: "request_to_join",
  logging_channel_id: "123456789012345679",
  name_template: "{game} with {user}",
  time_zone: "Europe/London",
  unique_names: true,
  game_aliases: "rl = Rocket League",
  random_names: "The Lobby",
  channel_template: "Lobby {n}",
};

describe("voice.config.get", () => {
  it("posts a signed get with the guild id and parses settings plus attribution", async () => {
    const { client, seen } = clientWith([
      jsonResponse(200, {
        ok: true,
        result: {
          settings: SETTINGS,
          version: 7,
          updated_by: "dashboard:100000000000000111",
          updated_at: "2026-10-20T12:00:00Z",
        },
        request_id: "r-get-1",
      }),
    ]);
    const result = await client.getVoiceConfig(GUILD_ID);
    expect(result).toEqual({
      ok: true,
      requestId: "r-get-1",
      settings: SETTINGS,
      version: 7,
      updatedBy: "dashboard:100000000000000111",
      updatedAt: "2026-10-20T12:00:00Z",
    });
    expect(seen).toHaveLength(1);
    expect(seen[0]!.url).toBe("https://bot-staging.internal.example/internal/actions");
    const body = JSON.parse(seen[0]!.init.body as string) as Record<string, string>;
    expect(body).toEqual({ action: "voice.config.get", guild_id: GUILD_ID });
    const headers = seen[0]!.init.headers as Record<string, string>;
    expect(headers["X-TWO-Signature"]).toMatch(/^sha256=[0-9a-f]{64}$/);
    // A read carries no idempotency key: absent, not blank.
    expect("Idempotency-Key" in headers).toBe(false);
  });

  it("accepts a never-changed config with null attribution", async () => {
    const { client } = clientWith([
      jsonResponse(200, {
        ok: true,
        result: { settings: SETTINGS, version: 1, updated_by: null, updated_at: null },
        request_id: "r-get-2",
      }),
    ]);
    const result = await client.getVoiceConfig(GUILD_ID);
    expect(result).toMatchObject({ ok: true, version: 1, updatedBy: null, updatedAt: null });
  });

  it("refuses a non-snowflake guild id before sending (terminal, no network)", async () => {
    const { client, fetchFn } = clientWith([]);
    await expect(client.getVoiceConfig("not-an-id")).rejects.toThrow(BotTerminalError);
    expect(fetchFn).not.toHaveBeenCalled();
  });

  it("throws a transport error on a success with no settings object", async () => {
    const { client } = clientWith([
      jsonResponse(200, {
        ok: true,
        result: { version: 7, updated_by: null, updated_at: null },
        request_id: "r-get-3",
      }),
    ]);
    await expect(client.getVoiceConfig(GUILD_ID)).rejects.toThrow(BotTransportError);
  });

  it("throws a transport error on a success with no integer version", async () => {
    const { client } = clientWith([
      jsonResponse(200, {
        ok: true,
        result: { settings: SETTINGS, updated_by: null, updated_at: null },
        request_id: "r-get-4",
      }),
    ]);
    await expect(client.getVoiceConfig(GUILD_ID)).rejects.toThrow(BotTransportError);
  });

  it("returns a bot failure as-is instead of throwing", async () => {
    const { client } = clientWith([
      jsonResponse(404, {
        ok: false,
        error: { code: "unknown_guild", message: "no such guild", retryable: false },
        request_id: "r-get-5",
      }),
    ]);
    const result = await client.getVoiceConfig(GUILD_ID);
    expect(result).toMatchObject({
      ok: false,
      code: "unknown_guild",
      status: 404,
      retryable: false,
    });
  });
});

describe("voice.config.set", () => {
  it("posts the settings blob with the expected version and a UUID key", async () => {
    const { client, seen } = clientWith([
      jsonResponse(200, { ok: true, result: { version: 8 }, request_id: "r-set-1" }),
    ]);
    const result = await client.setVoiceConfig(GUILD_ID, SETTINGS, 7, UUID);
    expect(result).toMatchObject({ ok: true, version: 8, replayed: false, requestId: "r-set-1" });
    expect(seen).toHaveLength(1);
    const body = JSON.parse(seen[0]!.init.body as string) as Record<string, string>;
    expect(body["action"]).toBe("voice.config.set");
    expect(body["guild_id"]).toBe(GUILD_ID);
    expect(body["expected_version"]).toBe("7");
    // One canonical JSON blob: the fourteen keys survive the string-only wire.
    expect(JSON.parse(body["settings"] ?? "{}")).toEqual(SETTINGS);
    const headers = seen[0]!.init.headers as Record<string, string>;
    expect(headers["Idempotency-Key"]).toBe(UUID);
  });

  it("reads the replayed flag on an idempotent replay", async () => {
    const { client } = clientWith([
      jsonResponse(
        200,
        { ok: true, result: { version: 8 }, request_id: "r-set-2" },
        { "Idempotent-Replay": "true" },
      ),
    ]);
    const result = await client.setVoiceConfig(GUILD_ID, SETTINGS, 7, UUID);
    expect(result).toMatchObject({ ok: true, replayed: true });
  });

  it("rejects a non-UUID idempotency key before sending", async () => {
    const { client, fetchFn } = clientWith([]);
    await expect(client.setVoiceConfig(GUILD_ID, SETTINGS, 7, "not-a-uuid")).rejects.toThrow(
      BotTerminalError,
    );
    expect(fetchFn).not.toHaveBeenCalled();
  });

  it("refuses a non-snowflake guild id before sending (terminal, no network)", async () => {
    const { client, fetchFn } = clientWith([]);
    await expect(client.setVoiceConfig("nope", SETTINGS, 7, UUID)).rejects.toThrow(
      BotTerminalError,
    );
    expect(fetchFn).not.toHaveBeenCalled();
  });

  it.each([0, -1, 1.5, Number.NaN])(
    "refuses a non-positive-integer expected version %s before sending",
    async (version) => {
      const { client, fetchFn } = clientWith([]);
      await expect(client.setVoiceConfig(GUILD_ID, SETTINGS, version, UUID)).rejects.toThrow(
        BotTerminalError,
      );
      expect(fetchFn).not.toHaveBeenCalled();
    },
  );

  it("throws a transport error on a success with no new version", async () => {
    const { client } = clientWith([
      jsonResponse(200, { ok: true, result: {}, request_id: "r-set-3" }),
    ]);
    await expect(client.setVoiceConfig(GUILD_ID, SETTINGS, 7, UUID)).rejects.toThrow(
      BotTransportError,
    );
  });

  it("returns a version conflict as-is so the route can re-read on the code", async () => {
    const { client } = clientWith([
      jsonResponse(409, {
        ok: false,
        error: { code: "version_conflict", message: "stale version", retryable: false },
        request_id: "r-set-4",
      }),
    ]);
    const result = await client.setVoiceConfig(GUILD_ID, SETTINGS, 7, UUID);
    expect(result).toMatchObject({
      ok: false,
      code: "version_conflict",
      status: 409,
      retryable: false,
    });
  });
});
