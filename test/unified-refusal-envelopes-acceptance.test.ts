async function profileHarness(logged: boolean) {
  const sessions = createMemorySessionStore();
  const token = newSessionToken();
  await sessions.create({
    tokenHash: await hashToken(token),
    userId: OWNER_ID,
    username: "alice",
    avatar: null,
    member: true,
    moderator: false,
    expiresAt: new Date(Date.now() + 3600_000),
  });
  const cookie = (
    await serializeSigned("__Host-two_session", token, SESSION_SECRET, {
      path: "/",
      secure: true,
      httpOnly: true,
      sameSite: "Lax",
    })
  ).split(";")[0]!;
  const store = createMemoryProfileStore([
    {
      id: OWNER_ID,
      username: "alice",
      avatar: null,
      bio: "Hi",
      games: ["Chess"],
      timezone: "UTC",
    },
  ]);
  const inner = profilesApp({
    sessionStore: sessions,
    store,
    accessLog: async () => true,
    throttle: async () => ({ limited: false }),
  });
  let client: { request: typeof inner.request } = inner;
  if (logged) {
    const router = new Hono<{ Bindings: Env }>();
    router.use("*", requestLog);
    router.route("/", inner);
    client = router;
  }
  const env = { APP_URL, SESSION_SECRET } as Env;
  return { client, env, cookie };
}

