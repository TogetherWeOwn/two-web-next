describe("expired-write recovery refusal", () => {
  it("logged JSON 401 uses unauthenticated with request_id and recovery", async () => {
    const res = await recoveryHarness(true, false).request(
      "/probe",
      { method: "POST", headers: { accept: "application/json", "cf-ray": RAY } },
      recoveryEnv,
    );
    expect(res.status).toBe(401);
    expect(res.headers.get("x-request-id")).toBe(RAY);
    expect(await res.json()).toEqual({
      error: "unauthenticated",
      recovery: "/auth/recover?next=%2Fevents",
      request_id: RAY,
    });
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });

  it("bare JSON 401 uses unauthenticated without request_id", async () => {
    const res = await recoveryHarness(false, false).request(
      "/probe",
      { method: "POST", headers: { accept: "application/json", "cf-ray": RAY } },
      recoveryEnv,
    );
    expect(res.status).toBe(401);
    expect(res.headers.get("x-request-id")).toBeNull();
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toEqual({ error: "unauthenticated", recovery: "/auth/recover?next=%2Fevents" });
    expect("request_id" in body).toBe(false);
  });

  it("logged jsonOnly 401 without headers uses unauthenticated with request_id", async () => {
    const res = await recoveryHarness(true, true).request(
      "/probe",
      { method: "POST", headers: { "cf-ray": RAY } },
      recoveryEnv,
    );
    expect(res.status).toBe(401);
    expect(await res.json()).toEqual({
      error: "unauthenticated",
      recovery: "/auth/recover?next=%2Fevents",
      request_id: RAY,
    });
  });

  it("native form POST still 303s to recovery (control)", async () => {
    const res = await recoveryHarness(true, false).request(
      "/probe",
      {
        method: "POST",
        headers: { "content-type": "application/x-www-form-urlencoded", "cf-ray": RAY },
      },
      recoveryEnv,
    );
    expect(res.status).toBe(303);
    expect(res.headers.get("location")).toBe("/auth/recover?next=%2Fevents");
  });
});

