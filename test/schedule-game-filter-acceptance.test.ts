const norm = (s: string): string => s.trim().toLowerCase();

// pg-proxy fake routing every calendar read by its SQL shape, plus the new
// distinct-games read (select distinct ... game ...) answered from the
// published-only fixture games. Game filtering applies only when the WHERE
// clause names "game": on base HEAD no such predicate exists (game ignored,
// unfiltered rows) so filtering assertions fail RED; with a correct Builder
// the predicate binds the game and the fixture filters exactly (unknown/blank
// correctly degrade by binding nothing).
function gameScheduleFixture(args: {
  upcoming?: (typeof events.$inferSelect)[];
  monthRows?: (typeof events.$inferSelect)[];
  past?: (typeof events.$inferSelect)[];
  source?: DiscordEventsSource;
}) {
  const upcoming = args.upcoming ?? [];
  const monthRows = args.monthRows ?? [];
  const past = args.past ?? [];
  const source = args.source ?? discordSource();
  const queries: { sql: string; params: unknown[] }[] = [];
  const columns = Object.keys(getTableColumns(events)) as (keyof typeof events.$inferSelect)[];
  const encode = (row: typeof events.$inferSelect) =>
    columns.map((k) => {
      const v = row[k];
      return v instanceof Date ? v.toISOString() : v;
    });
  const applyFilters = (
    rows: (typeof events.$inferSelect)[],
    sql: string,
    params: unknown[],
  ): (typeof events.$inferSelect)[] => {
    let out = rows;
    const qBound = params.find(
      (p): p is string => typeof p === "string" && p.startsWith("%") && p.endsWith("%"),
    );
    if (qBound) {
      const term = qBound.slice(1, -1).replace(/\\(.)/g, "$1").toLowerCase();
      out = out.filter(
        (r) =>
          r.title.toLowerCase().includes(term) ||
          (r.description ?? "").toLowerCase().includes(term),
      );
    }
    // Game filtering applies only when the WHERE clause names the game column:
    // the SELECT list always projects "game", so a full-SQL match would filter
    // every read. Timestamp bounds (Date objects or ISO strings) are never game
    // bindings. On base HEAD no game predicate exists, so rows pass through
    // unfiltered and filtering assertions fail RED.
    const wherePart = sql
      .split(/from "events"/i)
      .slice(1)
      .join(' from "events" ');
    if (/"game"/i.test(wherePart)) {
      const gameParam = params.find(
        (p): p is string =>
          typeof p === "string" &&
          !(p.startsWith("%") && p.endsWith("%")) &&
          !/^\d{4}-\d{2}-\d{2}[T ]/.test(p),
      );
      if (typeof gameParam === "string") {
        const want = norm(gameParam);
        out = out.filter((r) => r.game !== null && norm(r.game) === want);
      }
    }
    return out;
  };
  const db = drizzle(async (sql, params) => {
    queries.push({ sql, params: [...params] });
    if (sql.includes('from "rsvps"')) return { rows: [] };
    if (sql.startsWith('select "discord_event_id" from "events"')) {
      return {
        rows: [...upcoming, ...past]
          .filter((r) => params.includes(r.discordEventId))
          .map((r) => [r.discordEventId]),
      };
    }
    // The Builder's distinct-games list. Answered published-only by
    // construction; the tests additionally pin `published` + `limit` in the
    // issued SQL so a Builder that selects drafts or omits the bound fails.
    if (/select\s+distinct/i.test(sql) && /game/i.test(sql)) {
      const games = [
        ...new Set(
          [...upcoming, ...monthRows, ...past]
            .filter((r) => r.status === "published" && r.game !== null && r.game.trim() !== "")
            .map((r) => r.game!.trim()),
        ),
      ].sort((a, b) => a.localeCompare(b));
      const hasLimit = sql.includes("limit");
      const limit = hasLimit ? Number(params.at(-1)) : games.length;
      const bounded = Number.isSafeInteger(limit) ? games.slice(0, Math.max(0, limit)) : games;
      return { rows: bounded.map((g) => [g]) };
    }
    // The month-grid read is the only one with a bound starts_at upper bound.
    if (sql.includes('"starts_at" < $')) {
      const filtered = applyFilters(monthRows, sql, params);
      const hasLimit = sql.includes("limit");
      const limit = hasLimit ? Number(params.at(-1)) : filtered.length;
      const bounded = Number.isSafeInteger(limit) ? filtered.slice(0, limit) : filtered;
      return { rows: bounded.map(encode) };
    }
    let rows = /"ends_at" </.test(sql) ? past : upcoming;
    rows = applyFilters(rows, sql, params);
    if (/^select count/i.test(sql)) return { rows: [[rows.length]] };
    if (sql.includes("limit")) {
      const hasOffset = sql.includes(" offset ");
      const offset = hasOffset ? Number(params.at(-1)) : 0;
      const limit = Number(params.at(hasOffset ? -2 : -1));
      const start = Number.isSafeInteger(offset) && offset > 0 ? offset : 0;
      const end = Number.isSafeInteger(limit) ? start + limit : rows.length;
      rows = rows.slice(start, end);
    }
    return { rows: rows.map(encode) };
  });
  Object.assign(db, {
    transaction: async (fn: (tx: Db) => Promise<void>) =>
      fn({ execute: async () => {} } as unknown as Db),
  });
  const adminDb = db as unknown as Db;
  const env = {
    ...baseEnv,
    ADMIN_DB: adminDb,
    DISCORD_EVENTS: source,
  } as unknown as Env;
  return {
    db: adminDb,
    env,
    queries,
    source,
    request: (path: string, init?: RequestInit) => app.request(path, init, env),
  };
}

function selectFor(html: string): string | null {
  return (
    new RegExp(
      `<select\\b[^>]*data-testid="${GAME_FILTER_TESTID}"[^>]*>([\\s\\S]*?)</select>`,
    ).exec(html)?.[0] ?? null
  );
}

function optionsOf(selectHtml: string): { value: string; label: string; selected: boolean }[] {
  return [...selectHtml.matchAll(/<option\b([^>]*)>([\s\S]*?)<\/option>/g)].map((m) => {
    const attrs = m[1] ?? "";
    const value = /value="([^"]*)"/.exec(attrs)?.[1] ?? "";
    // Labels arrive HTML-escaped; decode the entities JSX emits so assertions
    // read stored names while the raw-HTML assertions below still pin escaping.
    const label = (m[2] ?? "")
      .replaceAll("&amp;", "&")
      .replaceAll("&lt;", "<")
      .replaceAll("&gt;", ">")
      .replaceAll("&quot;", '"')
      .replaceAll("&#x27;", "'")
      .trim();
    return { value, label, selected: /\bselected\b/.test(attrs) };
  });
}

function statusInner(html: string, testid: string): string | null {
  return (
    new RegExp(`<p\\b[^>]*data-testid="${testid}"[^>]*>([\\s\\S]*?)</p>`).exec(html)?.[1] ?? null
  );
}

function hrefFor(html: string, testid: string): string | null {
  const tag = new RegExp(`<a\\b[^>]*data-testid="${testid}"[^>]*>`).exec(html)?.[0];
  const href = tag && /href="([^"]+)"/.exec(tag)?.[1];
  return href ? href.replaceAll("&amp;", "&") : null;
}

function gameParamOf(href: string | null): string | null {
  if (!href) return null;
  try {
    return new URL(href, APP_URL).searchParams.get(GAME_PARAM);
  } catch {
    return null;
  }
}

