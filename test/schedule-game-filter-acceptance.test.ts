  queries.filter(
    (q) =>
      /from "events"/i.test(q.sql) &&
      !q.sql.includes('from "rsvps"') &&
      !q.sql.startsWith('select "discord_event_id"') &&
      !/select\s+distinct/i.test(q.sql) &&
      !/"ends_at" </.test(q.sql) &&
      !/"starts_at" < \$/.test(q.sql),
  );

const bindsGame = (query: { sql: string; params: unknown[] }, game: string): boolean =>
  query.params.some(
    (p): p is string =>
      typeof p === "string" && !(p.startsWith("%") && p.endsWith("%")) && norm(p) === norm(game),
  );

