// Acceptance-owned (test author): egress reads feeding /events.ics,
// /events.rss, /events.md and sitemap generation must cap rows in SQL.
//
// Contract pinned here (the builder chooses the exact cap inside it):
// - `listFeed` and `sitemapEvents` each issue one SELECT carrying a SQL
//   LIMIT whose value is between 103 and 1000 inclusive. The floor keeps the
//   established 103-event subscription collection whole (see
//   feed-equal-start-order.test.ts); the ceiling keeps egress bounded.
// - With 1100 eligible fixtures both reads return at most 1000 rows (and at
//   least 103), retaining the soonest rows in the existing order.
// - GET /events.ics and /events.rss stay 200 under the over-cap fixture,
//   with at most 1000 entries and ICS bytes bounded by the capped size.
// - Normal (under-cap) feeds are byte-for-byte the established behavior:
//   same eligibility (status scope, finite window, ends_at >= now), same
//   order, same keys. Those controls pass before and after the fix.
//
// Do not edit this file in the builder change; return incorrect tests to the
// acceptance card instead. Isolated test DB only.
import { drizzle } from "drizzle-orm/pg-proxy";
import { Hono } from "hono";
import { afterAll, afterEach, beforeAll, beforeEach, describe, expect, it, vi } from "vitest";
import { events } from "../src/db/admin-schema";
import type { Db } from "../src/db/index";
import type { Env } from "../src/env";
import { listFeed, sitemapEvents } from "../src/events/reads";
import { registerEventRoutes } from "../src/events/routes";
import {
  createMemberDataFixture,
  testDatabaseUrl,
  type MemberDataFixture,
} from "./helpers/member-data-db";

const raw = process.env.DATABASE_URL;
const url = raw ? testDatabaseUrl(raw).href : undefined;

const CAP_FLOOR = 103;
const CAP_CEILING = 1000;
const OVER_CAP = 1100;

const NOW = new Date("2030-01-10T20:00:00Z");
const key = (id: number) => String(id).padStart(26, "0");
type EventRow = typeof events.$inferSelect;
// Fixed-width titles keep per-event ICS/RSS bytes constant, so the byte
// bound below measures entries, not fixture text drift. Distinct ascending
// starts (one minute apart) make "soonest retained" unambiguous.
const row = (
  id: number,
  over: Partial<Pick<EventRow, "startsAt" | "endsAt" | "status">> = {},
): Partial<EventRow> & { eventKey: string; title: string; startsAt: Date; endsAt: Date } => ({
  id,
  eventKey: key(id),
  title: `Event ${String(id).padStart(4, "0")}`,
  startsAt: new Date(NOW.getTime() + id * 60_000),
  endsAt: new Date(NOW.getTime() + id * 60_000 + 2 * 3_600_000),
  status: "published",
  updatedAt: NOW,
  ...over,
});
const ids = (rows: Pick<EventRow, "id">[]) => rows.map((event) => event.id);
const range = (n: number) => Array.from({ length: n }, (_, index) => index + 1);

/** Run one read against a query-capturing pg-proxy and return its SQL LIMIT value. */
async function sqlLimitOf(run: (db: Db) => Promise<unknown>): Promise<number | null> {
  const seen: { sql: string; params: unknown[] }[] = [];
  const db = drizzle(async (sql, params) => {
    seen.push({ sql, params: [...params] });
    return { rows: [] };
  }) as unknown as Db;
  await run(db);
  expect(seen, "the read issues exactly one SELECT").toHaveLength(1);
  const [{ sql, params }] = seen as [{ sql: string; params: unknown[] }];
  const match = /limit\s+(?:\$(\d+)|(\d+))/i.exec(sql);
  if (!match) return null;
  if (match[2] !== undefined) return Number(match[2]);
  const value = params[Number(match[1]) - 1];
  return typeof value === "number" ? value : null;
}

describe("egress reads cap rows in SQL (hermetic query shape)", () => {
  it("listFeed issues a single SELECT with a SQL LIMIT inside the pinned range", async () => {
    const limit = await sqlLimitOf((db) => listFeed(db, ["published", "cancelled"], NOW));
    expect(limit, "listFeed must carry a SQL LIMIT").not.toBeNull();
    expect(limit!).toBeGreaterThanOrEqual(CAP_FLOOR);
    expect(limit!).toBeLessThanOrEqual(CAP_CEILING);
  });

  it("sitemapEvents issues a single SELECT with a SQL LIMIT inside the pinned range", async () => {
    const limit = await sqlLimitOf((db) => sitemapEvents(db));
    expect(limit, "sitemapEvents must carry a SQL LIMIT").not.toBeNull();
    expect(limit!).toBeGreaterThanOrEqual(CAP_FLOOR);
    expect(limit!).toBeLessThanOrEqual(CAP_CEILING);
  });
});

describe.skipIf(!url)("egress reads under over-cap fixtures (isolated test DB)", () => {
  let fixture: MemberDataFixture;
  let env: Env;
  const readSession = vi.fn(async () => null);
  const app = new Hono<{ Bindings: Env }>();
  registerEventRoutes(app, readSession, readSession);
  const request = (path: string) => app.request(path, {}, env);

  beforeAll(async () => {
    fixture = await createMemberDataFixture(url!, { max: 2 });
    env = {
      APP_URL: "https://next.example.test",
      DISCORD_CLIENT_ID: "fixture",
      DISCORD_CLIENT_SECRET: "fixture",
      DISCORD_GUILD_ID: "fixture",
      DISCORD_INVITE_URL: "https://discord.gg/fixture",
      DISCORD_BOT_TOKEN: "fixture",
      SESSION_SECRET: "fixture",
      ADMIN_DB: fixture.db,
    } as unknown as Env;
  });
  afterAll(async () => {
    await fixture?.dispose();
  });
  beforeEach(async () => {
    vi.useFakeTimers({ toFake: ["Date"] });
    vi.setSystemTime(NOW);
    readSession.mockClear();
    await fixture.reset();
  });
  afterEach(() => {
    vi.useRealTimers();
  });

  async function seed(count: number) {
    for (let start = 1; start <= count; start += 200) {
      const chunk = range(Math.min(200, count - start + 1)).map((offset) =>
        row(start + offset - 1),
      );
      await fixture.db.insert(events).values(chunk);
    }
  }

  it("listFeed returns bounded rows, retaining the soonest in order", async () => {
    await seed(OVER_CAP);
    const rows = await listFeed(fixture.db, ["published", "cancelled"], NOW);
    expect(rows.length).toBeLessThan(OVER_CAP);
    expect(rows.length).toBeLessThanOrEqual(CAP_CEILING);
    expect(rows.length).toBeGreaterThanOrEqual(CAP_FLOOR);
    expect(ids(rows)).toEqual(range(rows.length));
  });

  it("sitemapEvents returns bounded rows, retaining the earliest in order", async () => {
    await seed(OVER_CAP);
    const rows = await sitemapEvents(fixture.db);
    expect(rows.length).toBeLessThan(OVER_CAP);
    expect(rows.length).toBeLessThanOrEqual(CAP_CEILING);
    expect(rows.length).toBeGreaterThanOrEqual(CAP_FLOOR);
    expect(rows.map((r) => r.key)).toEqual(range(rows.length).map(key));
    expect(rows.every((r) => r.status === "published")).toBe(true);
  });

  it("GET /events.ics and /events.rss stay 200 with bounded entries and ICS bytes", async () => {
    // Measure the marginal bytes of one calendar entry from normal feeds so
    // the over-cap byte bound derives from the established format.
    await seed(1);
    const one = await request("/events.ics");
    expect(one.status).toBe(200);
    const bytesOne = new TextEncoder().encode(await one.text()).length;
    await fixture.reset();
    await seed(10);
    const ten = await request("/events.ics");
    expect(ten.status).toBe(200);
    const bytesTen = new TextEncoder().encode(await ten.text()).length;
    const marginal = (bytesTen - bytesOne) / 9;
    expect(marginal).toBeGreaterThan(0);
    const byteBound = Math.ceil(bytesOne - marginal + CAP_CEILING * marginal) + 64;

    await fixture.reset();
    await seed(OVER_CAP);
    const ics = await request("/events.ics");
    expect(ics.status).toBe(200);
    const icsBody = await ics.text();
    const vevents = [...icsBody.matchAll(/BEGIN:VEVENT/g)].length;
    expect(vevents).toBeLessThan(OVER_CAP);
    expect(vevents).toBeLessThanOrEqual(CAP_CEILING);
    expect(vevents).toBeGreaterThanOrEqual(CAP_FLOOR);
    expect(new TextEncoder().encode(icsBody).length).toBeLessThanOrEqual(byteBound);
    // Soonest retained: the first fixture is present, the last is not.
    expect(icsBody).toContain(`UID:${key(1)}@`);
    expect(icsBody).not.toContain(`UID:${key(OVER_CAP)}@`);

    const rss = await request("/events.rss");
    expect(rss.status).toBe(200);
    const items = [...(await rss.text()).matchAll(/<item>/g)].length;
    expect(items).toBeLessThan(OVER_CAP);
    expect(items).toBeLessThanOrEqual(CAP_CEILING);
    expect(items).toBeGreaterThanOrEqual(CAP_FLOOR);
  });

  it("normal feeds are unchanged: eligibility, order and keys below the cap", async () => {
    await fixture.db
      .insert(events)
      .values([
        row(3),
        row(1),
        row(2),
        row(4, { status: "cancelled" }),
        row(5, { status: "draft" }),
        row(6, { endsAt: new Date(NOW.getTime() - 1) }),
        row(7, { status: "past" }),
      ]);
    expect(ids(await listFeed(fixture.db, ["published"], NOW))).toEqual([1, 2, 3]);
    expect(ids(await listFeed(fixture.db, ["published", "cancelled"], NOW))).toEqual([1, 2, 3, 4]);
    // Sitemap scope is status-only (no ends_at filter): the ended published
    // row stays listed, in starts_at order.
    expect((await sitemapEvents(fixture.db)).map((r) => r.key)).toEqual([
      key(1),
      key(2),
      key(3),
      key(6),
    ]);

    const ics = await request("/events.ics");
    expect(ics.status).toBe(200);
    const icsKeys = [...(await ics.text()).matchAll(/\r\nUID:([^@]+)@/g)].map((m) => m[1]);
    expect(icsKeys).toEqual([key(1), key(2), key(3), key(4)]);
    const rss = await request("/events.rss");
    expect(rss.status).toBe(200);
    const rssKeys = [
      ...(await rss.text()).matchAll(/<guid isPermaLink="true">[^<]+\/e\/([^<]+)<\/guid>/g),
    ].map((m) => m[1]);
    expect(rssKeys).toEqual([key(1), key(2), key(3)]);
  });

  it("keeps the established 103-event subscription collection whole", async () => {
    await seed(CAP_FLOOR);
    expect(ids(await listFeed(fixture.db, ["published"], NOW))).toEqual(range(CAP_FLOOR));
    const ics = await request("/events.ics");
    expect(ics.status).toBe(200);
    expect([...(await ics.text()).matchAll(/BEGIN:VEVENT/g)]).toHaveLength(CAP_FLOOR);
  });
});
