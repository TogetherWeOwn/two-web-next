// Normalize for selector/declaration matching: strip comments and quotes,
// tighten punctuation spacing. Testid values keep their case.
const tight = (css: string): string =>
  css
    .replace(/\/\*[\s\S]*?\*\//g, "")
    .replace(/["']/g, "")
    .replace(/\s*([=:{},;>+~])\s*/g, "$1")
    .replace(/\s+/g, " ");

// Extract every @media print span (brace-matched) and the screen remainder.
function splitPrintCss(css: string): { print: string; screen: string } {
  const prints: string[] = [];
  const screens: string[] = [];
  let i = 0;
  let cursor = 0;
  while (true) {
    const at = css.indexOf("@media", cursor);
    if (at === -1) break;
    const open = css.indexOf("{", at);
    if (open === -1) break;
    const prelude = css.slice(at, open);
    let depth = 0;
    let j = open;
    for (; j < css.length; j++) {
      if (css[j] === "{") depth++;
      else if (css[j] === "}") {
        depth--;
        if (depth === 0) break;
      }
    }
    const close = j < css.length ? j : css.length - 1;
    screens.push(css.slice(cursor, at));
    if (/print/.test(prelude) && !/max-width|min-width/.test(prelude)) {
      prints.push(css.slice(open + 1, close));
    } else {
      screens.push(css.slice(at, close + 1));
    }
    cursor = close + 1;
    i++;
    if (i > 50 || cursor >= css.length) break;
  }
  screens.push(css.slice(cursor));
  return { print: prints.join("\n"), screen: screens.join("\n") };
}

interface PrintRule {
  selector: string;
  decls: string;
}

// Top-level `selector { decls }` rules inside the print spans.
function printRules(printCss: string): PrintRule[] {
  const rules: PrintRule[] = [];
  let depth = 0;
  let selectorStart = 0;
  let declStart = -1;
  let selector = "";
  for (let j = 0; j < printCss.length; j++) {
    const ch = printCss[j];
    if (ch === "{") {
      if (depth === 0) {
        selector = printCss.slice(selectorStart, j);
        declStart = j + 1;
      }
      depth++;
    } else if (ch === "}") {
      depth--;
      if (depth === 0 && declStart >= 0) {
        rules.push({ selector: tight(selector), decls: tight(printCss.slice(declStart, j)) });
        selectorStart = j + 1;
        declStart = -1;
      }
    }
  }
  return rules;
}

const printHidden = (rules: PrintRule[], hook: string): boolean =>
  rules.some((r) => r.selector.includes(hook) && /display:none/.test(r.decls));

