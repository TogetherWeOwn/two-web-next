const familyOf = (sql: string): string => {
  if (sql.includes('from "rsvps"')) return "rsvps";
  if (sql.startsWith('select "discord_event_id"')) return "discord-probe";
  if (/select\s+distinct/i.test(sql)) return "distinct";
  if (sql.includes('"starts_at" < $')) return "month";
  if (/^select count/i.test(sql)) return "count";
  return "page";
};

