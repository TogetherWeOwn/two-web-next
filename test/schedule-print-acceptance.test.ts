function sectionInner(html: string, sectionTestid: string): string | null {
  const m = new RegExp(
    `<section\\b[^>]*data-testid="${sectionTestid}"[^>]*>([\\s\\S]*?)</section>`,
  ).exec(html);
  return m?.[1] ?? null;
}

function stampInner(html: string, stampTestid: string): string | null {
  const m = new RegExp(`<p\\b[^>]*data-testid="${stampTestid}"[^>]*>([\\s\\S]*?)</p>`).exec(html);
  return m?.[1] ?? null;
}

function stampTag(html: string, stampTestid: string): string | null {
  return new RegExp(`<p\\b[^>]*data-testid="${stampTestid}"[^>]*>`).exec(html)?.[0] ?? null;
}

const stripTags = (inner: string): string =>
  inner
    .replace(/<[^>]*>/g, " ")
    .replace(/&quot;/g, '"')
    .replace(/&#x27;/g, "'")
    .replace(/&lt;/g, "<")
    .replace(/&gt;/g, ">")
    .replace(/&amp;/g, "&")
    .replace(/\s+/g, " ")
    .trim();

const stampText = (html: string, stampTestid: string): string | null => {
  const inner = stampInner(html, stampTestid);
  return inner === null ? null : stripTags(inner);
};

function stampHrefs(html: string, stampTestid: string): string[] {
  const inner = stampInner(html, stampTestid) ?? "";
  return [...inner.matchAll(/href="([^"]*)"/g)].map((m) => m[1]!.replaceAll("&amp;", "&"));
}

function stampIsScreenHidden(html: string, stampTestid: string): boolean {
  const tag = stampTag(html, stampTestid);
  if (!tag) return false;
  if (/\bhidden\b/.test(tag)) return true;
  const cls = /class="([^"]*)"/.exec(tag)?.[1] ?? "";
  if (/(sr-only|visually-hidden)/.test(cls)) return true;
  const classes = cls.split(/\s+/).filter(Boolean);
  const { screen } = splitPrintCss(readScheduleCss());
  return printRules(screen).some(
    (r) =>
      (r.selector.includes(stampTestid) || classes.some((c) => r.selector.includes(`.${c}`))) &&
      /display:none/.test(r.decls),
  );
}

