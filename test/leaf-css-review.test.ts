// Missing or current-tree-only evidence must not hide a theme-only CSP change.
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

const root = resolve(import.meta.dirname, "..");
const script = join(root, "ci/leaf-css-review.mjs");
const scratch: string[] = [];
afterEach(() => {
  for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true });
});

function fixture() {
  const dir = mkdtempSync(join(tmpdir(), "leaf-css-review-test-"));
  scratch.push(dir);
  for (const sub of ["ci", "public"]) mkdirSync(join(dir, sub));
  writeFileSync(
    join(dir, "ci/build-leaf-css.mjs"),
    readFileSync(join(root, "ci/build-leaf-css.mjs")),
  );
  writeFileSync(join(dir, "public/styles.css"), "body { color: black; }");
  writeFileSync(join(dir, "public/theme-tokens.css"), ":root { --accent: lime; }");
  writeFileSync(join(dir, "public/theme.css"), ".hero { display: grid; }");
  const git = (...args: string[]) =>
    execFileSync("git", args, { cwd: dir, encoding: "utf8" }).trim();
  git("init", "-q");
  const commit = () => {
    git("add", ".");
    git(
      "-c",
      "user.name=Fixture",
      "-c",
      "user.email=fixture@example.test",
      "commit",
      "-qm",
      "fixture",
    );
    return git("rev-parse", "HEAD");
  };
  const base = commit();
  const run = (head = base, baseRef = base) =>
    spawnSync(process.execPath, [script, baseRef, head], {
      cwd: dir,
      encoding: "utf8",
      env: { ...process.env, GITHUB_STEP_SUMMARY: join(dir, "summary.md") },
      timeout: 15000,
    });
  return { dir, base, commit, run };
}

describe("generated leaf CSS review evidence", () => {
  it("reports unchanged generated bytes with both immutable revisions", () => {
    const { base, run } = fixture();
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    expect(report).toMatchObject({ version: 1, ok: true, changed: false });
    expect(report.base.sha).toBe(base);
    expect(report.head.sha).toBe(base);
    expect(report.base.sha256).toBe(report.head.sha256);
  });

  it("surfaces a theme-only CSP hash change from the two committed snapshots", () => {
    const { dir, base, commit, run } = fixture();
    writeFileSync(join(dir, "public/theme.css"), ".hero { display: flex; }");
    const head = commit();
    // Dirty worktree bytes must not masquerade as reviewed head bytes.
    writeFileSync(join(dir, "public/theme.css"), "uncommitted");
    const result = run(head);
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    const hash = (theme: string) =>
      createHash("sha256")
        .update(`body { color: black; }\n:root { --accent: lime; }\n${theme}`)
        .digest("base64");
    expect(report.changed).toBe(true);
    expect(report.base).toMatchObject({ sha: base, sha256: hash(".hero { display: grid; }") });
    expect(report.head).toMatchObject({ sha: head, sha256: hash(".hero { display: flex; }") });
    const summary = readFileSync(join(dir, "summary.md"), "utf8");
    expect(summary).toContain(base);
    expect(summary).toContain(head);
    expect(summary).toContain(`sha256-${report.base.sha256}`);
    expect(summary).toContain(`sha256-${report.head.sha256}`);
    expect(summary).toContain("changed");
  });

  it("fails closed with remediation when the base revision is unavailable", () => {
    const { run } = fixture();
    const result = run(undefined, "0".repeat(40));
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      version: 1,
      ok: false,
      error_code: "leaf_css_review_failed",
      retryable: false,
      next_action: expect.stringContaining("revision"),
    });
  });

  it("runs the revision's real generator and rejects unsafe CSS", () => {
    const { dir, commit, run } = fixture();
    writeFileSync(join(dir, "public/theme.css"), "</style><script>unsafe</script>");
    const result = run(commit());
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      ok: false,
      error_code: "leaf_css_review_failed",
    });
  });
});
