// Missing or current-tree-only evidence must not hide a theme-only CSP change.
import { execFileSync, spawnSync } from "node:child_process";
import { createHash } from "node:crypto";
import { chmodSync, mkdtempSync, mkdirSync, readFileSync, rmSync, writeFileSync } from "node:fs";
import { tmpdir } from "node:os";
import { join, resolve } from "node:path";
import { afterEach, describe, expect, it } from "vitest";

const root = resolve(import.meta.dirname, "..");
const script = join(root, "ci/leaf-css-review.mjs");
const scratch: string[] = [];
afterEach(() => {
  for (const dir of scratch.splice(0)) rmSync(dir, { recursive: true, force: true });
});

function fixture() {
  const dir = mkdtempSync(join(tmpdir(), "leaf-css-review-test-"));
  scratch.push(dir);
  for (const sub of ["ci", "public"]) mkdirSync(join(dir, sub));
  writeFileSync(
    join(dir, "ci/build-leaf-css.mjs"),
    readFileSync(join(root, "ci/build-leaf-css.mjs")),
  );
  writeFileSync(join(dir, "public/styles.css"), "body { color: black; }");
  writeFileSync(join(dir, "public/theme-tokens.css"), ":root { --accent: lime; }");
  writeFileSync(join(dir, "public/theme.css"), ".hero { display: grid; }");
  const git = (...args: string[]) =>
    execFileSync("git", args, { cwd: dir, encoding: "utf8" }).trim();
  git("init", "-q");
  const commit = () => {
    git("add", ".");
    git(
      "-c",
      "user.name=Fixture",
      "-c",
      "user.email=fixture@example.test",
      "commit",
      "-qm",
      "fixture",
    );
    return git("rev-parse", "HEAD");
  };
  const base = commit();
  const run = (head = base, baseRef = base, env: NodeJS.ProcessEnv = {}) =>
    spawnSync(process.execPath, [script, baseRef, head], {
      cwd: dir,
      encoding: "utf8",
      env: { ...process.env, GITHUB_STEP_SUMMARY: join(dir, "summary.md"), ...env },
      timeout: 15000,
    });
  return { dir, base, commit, run };
}

describe("generated leaf CSS review evidence", () => {
  it("reports unchanged generated bytes with both immutable revisions", () => {
    const { base, run } = fixture();
    const result = run();
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    expect(report).toMatchObject({ version: 1, ok: true, changed: false });
    expect(report.base.sha).toBe(base);
    expect(report.head.sha).toBe(base);
    expect(report.base.sha256).toBe(report.head.sha256);
  });

  it("compares a historical literal with the packed representation", () => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    writeFileSync(
      generator,
      readFileSync(generator, "utf8").replace(
        'const initializer = packed ? `${literal}.split("~").join(".base-theme")` : literal;',
        "const initializer = JSON.stringify(css);",
      ),
    );
    const historical = commit();
    const result = run(base, historical);
    expect(result.status, result.stderr).toBe(0);
    expect(JSON.parse(result.stdout)).toMatchObject({ ok: true, changed: false });
  });

  it.each([
    ["altered decoder", "text.replace('.join(\".base-theme\")', '.join(\".other\")')"],
    [
      "trailing expression",
      "text.replace(';\\nexport const LEAF_CRITICAL_CSS_SHA256', '+\"x\";\\nexport const LEAF_CRITICAL_CSS_SHA256')",
    ],
    ["changed bytes", 'text.replace("body { color: black; }", "body { color: white; }")'],
    ["changed hash", 'text.replace(sha256, "A".repeat(43) + "=")'],
  ])("rejects %s in generated snapshots", (_name, mutation) => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    const source = readFileSync(generator, "utf8").replace(
      "writeFileSync(join(repoRoot, OUT), text);",
      `writeFileSync(join(repoRoot, OUT), ${mutation});`,
    );
    writeFileSync(generator, source);
    const altered = commit();
    for (const result of [run(altered, base), run(base, altered)]) {
      expect(result.status).toBe(1);
      expect(JSON.parse(result.stdout)).toMatchObject({
        ok: false,
        error_code: "leaf_css_review_failed",
      });
    }
  });

  it.each(["base", "head"])("rejects coherent scratch-input mutation on the %s side", (side) => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    writeFileSync(
      generator,
      readFileSync(generator, "utf8").replace(
        "export function build() {",
        'export function build() {\n  writeFileSync(join(repoRoot, "public/styles.css"), "mutated scratch CSS");',
      ),
    );
    const altered = commit();
    const result = side === "base" ? run(base, altered) : run(altered, base);
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout).detail).toContain("does not match revision sources");
  });

  it.each([
    ["changed byte", 'css.replace("black", "white")'],
    ["reordered sources", 'css.split("\\n").reverse().join("\\n")'],
    ["prefix", '"prefix" + css'],
    ["suffix", 'css + "suffix"'],
  ])("rejects coherent %s outside the source recipes on either side", (_name, expression) => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    const original = 'const sha256 = createHash("sha256").update(css, "utf8").digest("base64");';
    const source = readFileSync(generator, "utf8");
    expect(source).toContain(original);
    writeFileSync(
      generator,
      source
        .replace("const css =", "let css =")
        .replace(original, `css = ${expression};\n  ${original}`),
    );
    const altered = commit();
    for (const result of [run(altered, base), run(base, altered)]) {
      expect(result.status).toBe(1);
      expect(JSON.parse(result.stdout).detail).toContain("does not match revision sources");
    }
  });

  it.each(["base", "head"])("rejects a missing mandatory blob on the %s side", (side) => {
    const { dir, base, commit, run } = fixture();
    rmSync(join(dir, "public/theme.css"));
    const missing = commit();
    const result = side === "base" ? run(base, missing) : run(missing, base);
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      ok: false,
      error_code: "leaf_css_review_failed",
    });
  });

  it.each(["base", "head"])("rejects an invalid optional entry on the %s side", (side) => {
    const { dir, base, commit, run } = fixture();
    mkdirSync(join(dir, "assets/leaf-only.css"), { recursive: true });
    writeFileSync(join(dir, "assets/leaf-only.css/nested"), "not a blob");
    const invalid = commit();
    const result = side === "base" ? run(base, invalid) : run(invalid, base);
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout).detail).toContain("invalid optional source entry");
  });

  it.each(["ls-tree", "show"])(
    "fails closed when optional Git %s fails on either side",
    (command) => {
      const { dir, commit, run } = fixture();
      mkdirSync(join(dir, "assets"));
      writeFileSync(join(dir, "assets/leaf-only.css"), "optional");
      const base = commit();
      writeFileSync(join(dir, "public/theme.css"), "changed");
      const head = commit();
      const bin = join(dir, "bin");
      mkdirSync(bin);
      const git = execFileSync("which", ["git"], { encoding: "utf8" }).trim();
      const wrapper = join(bin, "git");
      writeFileSync(
        wrapper,
        `#!/bin/sh
if [ "$1" = "$FAIL_COMMAND" ]; then
  case "$*" in *"$FAIL_SHA"*"assets/leaf-only.css"*) exit 1 ;; esac
fi
exec "$REAL_GIT" "$@"
`,
      );
      chmodSync(wrapper, 0o755);
      for (const sha of [base, head]) {
        const result = run(head, base, {
          PATH: `${bin}:${process.env.PATH}`,
          REAL_GIT: git,
          FAIL_COMMAND: command,
          FAIL_SHA: sha,
        });
        expect(result.status).toBe(1);
        expect(JSON.parse(result.stdout)).toMatchObject({
          ok: false,
          error_code: "leaf_css_review_failed",
        });
      }
    },
  );

  it.each(["base", "head"])("rejects invalid UTF-8 source bytes on the %s side", (side) => {
    const { dir, base, commit, run } = fixture();
    writeFileSync(join(dir, "public/theme.css"), Buffer.from([0xff]));
    const invalid = commit();
    const result = side === "base" ? run(base, invalid) : run(invalid, base);
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      ok: false,
      error_code: "leaf_css_review_failed",
    });
  });

  it("reports every matching recipe when an optional seam is empty and unused", () => {
    const { dir, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    writeFileSync(generator, readFileSync(generator, "utf8").replace('.join("\\n")', '.join("")'));
    mkdirSync(join(dir, "assets"));
    writeFileSync(join(dir, "assets/leaf-only.css"), "");
    const head = commit();
    const result = run(head);
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    expect(report.base.recipes).toEqual(["three-lf"]);
    expect(report.head.recipes).toEqual(["three-empty", "four-empty"]);
    expect(report.changed).toBe(true);
  });

  it("surfaces a theme-only CSP hash change from the two committed snapshots", () => {
    const { dir, base, commit, run } = fixture();
    writeFileSync(join(dir, "public/theme.css"), ".hero { display: flex; }");
    const head = commit();
    // Dirty worktree bytes must not masquerade as reviewed head bytes.
    writeFileSync(join(dir, "public/theme.css"), "uncommitted");
    const result = run(head);
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    const hash = (theme: string) =>
      createHash("sha256")
        .update(`body { color: black; }\n:root { --accent: lime; }\n${theme}`)
        .digest("base64");
    expect(report.changed).toBe(true);
    expect(report.base).toMatchObject({ sha: base, sha256: hash(".hero { display: grid; }") });
    expect(report.head).toMatchObject({ sha: head, sha256: hash(".hero { display: flex; }") });
    const summary = readFileSync(join(dir, "summary.md"), "utf8");
    expect(summary).toContain(base);
    expect(summary).toContain(head);
    expect(summary).toContain(`sha256-${report.base.sha256}`);
    expect(summary).toContain(`sha256-${report.head.sha256}`);
    expect(summary).toContain("changed");
  });

  it("fails closed with remediation when the base revision is unavailable", () => {
    const { run } = fixture();
    const result = run(undefined, "0".repeat(40));
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      version: 1,
      ok: false,
      error_code: "leaf_css_review_failed",
      retryable: false,
      next_action: expect.stringContaining("revision"),
    });
  });

  it("runs the revision's real generator and rejects unsafe CSS", () => {
    const { dir, commit, run } = fixture();
    writeFileSync(join(dir, "public/theme.css"), "</style><script>unsafe</script>");
    const result = run(commit());
    expect(result.status).toBe(1);
    expect(JSON.parse(result.stdout)).toMatchObject({
      ok: false,
      error_code: "leaf_css_review_failed",
    });
  });

  it("snapshots each revision with its own generator, not the head's", () => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    // Generator-only change, CSS untouched: the CSP hash must still move.
    writeFileSync(generator, readFileSync(generator, "utf8").replace('.join("\\n")', '.join("")'));
    const head = commit();
    const result = run(head);
    expect(result.status, result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    const hash = (separator: string) =>
      createHash("sha256")
        .update(
          ["body { color: black; }", ":root { --accent: lime; }", ".hero { display: grid; }"].join(
            separator,
          ),
        )
        .digest("base64");
    expect(report.changed).toBe(true);
    expect(report.base).toMatchObject({ sha: base, sha256: hash("\n") });
    expect(report.head).toMatchObject({ sha: head, sha256: hash("") });
  });

  it("copies the leaf-only seam only for revisions whose generator reads it", () => {
    const { dir, base, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    writeFileSync(
      generator,
      readFileSync(generator, "utf8").replace(
        '"public/theme.css"]',
        '"public/theme.css", "assets/leaf-only.css"]',
      ),
    );
    mkdirSync(join(dir, "assets"));
    writeFileSync(join(dir, "assets/leaf-only.css"), "@media print { .leaf { margin: 0; } }");
    const head = commit();
    // Dirty worktree bytes must not masquerade as reviewed head bytes.
    writeFileSync(join(dir, "assets/leaf-only.css"), "uncommitted");
    const result = run(head);
    expect(result.status, result.stdout + result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    expect(report.changed).toBe(true);
    const hash = (parts: string[]) =>
      createHash("sha256").update(parts.join("\n")).digest("base64");
    const rules = [
      "body { color: black; }",
      ":root { --accent: lime; }",
      ".hero { display: grid; }",
    ];
    // Pin the seam bytes' effect on the evidence, so an empty/wrong copy fails.
    expect(report.base).toMatchObject({ sha: base, sha256: hash(rules) });
    expect(report.head).toMatchObject({
      sha: head,
      sha256: hash([...rules, "@media print { .leaf { margin: 0; } }"]),
    });
  });

  it("pins the leaf-only seam bytes to the requested revision", () => {
    const { dir, commit, run } = fixture();
    const generator = join(dir, "ci/build-leaf-css.mjs");
    writeFileSync(
      generator,
      readFileSync(generator, "utf8").replace(
        '"public/theme.css"]',
        '"public/theme.css", "assets/leaf-only.css"]',
      ),
    );
    mkdirSync(join(dir, "assets"));
    // Both revisions carry the seam with different bytes: a HEAD read would
    // snapshot base with head's bytes, and a working-tree read with uncommitted bytes.
    writeFileSync(join(dir, "assets/leaf-only.css"), "@media print { .leaf { margin: 1px; } }");
    const seamBase = commit();
    writeFileSync(join(dir, "assets/leaf-only.css"), "@media print { .leaf { margin: 0; } }");
    const head = commit();
    writeFileSync(join(dir, "assets/leaf-only.css"), "uncommitted");
    const result = run(head, seamBase);
    expect(result.status, result.stdout + result.stderr).toBe(0);
    const report = JSON.parse(result.stdout);
    expect(report.changed).toBe(true);
    const hash = (parts: string[]) =>
      createHash("sha256").update(parts.join("\n")).digest("base64");
    const rules = [
      "body { color: black; }",
      ":root { --accent: lime; }",
      ".hero { display: grid; }",
    ];
    expect(report.base).toMatchObject({
      sha: seamBase,
      sha256: hash([...rules, "@media print { .leaf { margin: 1px; } }"]),
    });
    expect(report.head).toMatchObject({
      sha: head,
      sha256: hash([...rules, "@media print { .leaf { margin: 0; } }"]),
    });
  });

  it("compares the merge queue's base and head revisions on merge_group runs", () => {
    // merge_group payloads carry no pull_request SHAs and no `before`, so a
    // chain without merge_group refs resolves both args to github.sha and the
    // CLI reports changed:false for every queued change.
    const workflow = readFileSync(join(root, ".github/workflows/ci.yml"), "utf8");
    const stepStart = workflow.indexOf("Generated leaf-CSS and CSP hash review delta");
    expect(stepStart).toBeGreaterThan(-1);
    const stepEnd = workflow.indexOf("- name:", stepStart + 1);
    const step = workflow.slice(stepStart, stepEnd === -1 ? undefined : stepEnd);
    expect(step).toContain("github.event.merge_group.base_sha");
    expect(step).toContain("github.event.merge_group.head_sha");
  });
});
