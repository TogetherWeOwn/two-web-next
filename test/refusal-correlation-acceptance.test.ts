describe("refusals on product routes", () => {
  async function nonModeratorCookie(
    store: ReturnType<typeof createMemorySessionStore>,
  ): Promise<string> {
    const token = newSessionToken();
    await store.create({
      tokenHash: await hashToken(token),
      userId: "100000000000000333",
      username: "pleb",
      avatar: null,
      member: true,
      moderator: false,
      expiresAt: new Date(Date.now() + 3600_000),
    });
    return (
      await serializeSigned("__Host-two_session", token, SESSION_SECRET, {
        path: "/",
        secure: true,
        httpOnly: true,
        sameSite: "Lax",
      })
    ).split(";")[0]!;
  }

  it("non-moderator admin JSON refusal correlates end to end: header, envelope and log share one id", async () => {
    const store = createMemorySessionStore();
    const res = await app.request(
      "/admin",
      {
        headers: {
          cookie: await nonModeratorCookie(store),
          accept: "application/json",
          "cf-ray": RAY,
        },
      },
      { ...baseEnv, SESSION_STORE: store },
    );
    expect(res.status).toBe(403);
    expect(res.headers.get("x-request-id")).toBe(RAY);
    const text = await res.text();
    const body = JSON.parse(text) as Record<string, unknown>;
    expect(body).toMatchObject({ error: "forbidden" });
    expect(body.request_id).toBe(RAY);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });

  it("oversized logout body answers 413 JSON with request_id", async () => {
    const res = await app.request(
      "/logout",
      {
        method: "POST",
        headers: {
          origin: APP_URL,
          accept: "application/json",
          "cf-ray": RAY,
        },
        body: "x".repeat(4096 + 1),
      },
      { ...baseEnv, SESSION_STORE: createMemorySessionStore() },
    );
    expect(res.status).toBe(413);
    expect(res.headers.get("content-type")).toContain("application/json");
    expect(res.headers.get("x-request-id")).toBe(RAY);
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toMatchObject({ reason: "payload_too_large" });
    expect(body.request_id).toBe(RAY);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });
});

describe("negotiated logout 503", () => {
  const refused = () =>
    Object.assign(new Error("connect ECONNREFUSED 127.0.0.1:5432"), {
      code: "ECONNREFUSED",
    });

  async function logoutFixture() {
    const store = createMemorySessionStore();
    const token = newSessionToken();
    await store.create({
      tokenHash: await hashToken(token),
      userId: "100000000000000444",
      username: "signer",
      avatar: null,
      member: true,
      moderator: false,
      expiresAt: new Date(Date.now() + 3600_000),
    });
    const cookie = (
      await serializeSigned("__Host-two_session", token, SESSION_SECRET, {
        path: "/",
        secure: true,
        httpOnly: true,
        sameSite: "Lax",
      })
    ).split(";")[0]!;
    return { store, cookie, token, bindings: { ...baseEnv, SESSION_STORE: store } };
  }

  const post = (cookie: string, accept: string, bindings: Env) =>
    app.request(
      "/logout",
      { method: "POST", headers: { cookie, origin: APP_URL, accept, "cf-ray": RAY } },
      bindings,
    );

  it.each([
    refused(),
    Object.assign(new Error("permission denied"), { code: "42501" }),
    new TypeError("private revocation bug"),
  ])(
    "fetch caller gets a correlated JSON 503 with no cookie clear and no driver detail: %s",
    async (error) => {
      const { store, cookie, token, bindings } = await logoutFixture();
      vi.spyOn(store, "revoke").mockRejectedValue(error);
      const res = await post(cookie, "application/json", bindings);
      expect(store.revoke).toHaveBeenCalledOnce();
      expect(res.status).toBe(503);
      expect(res.headers.get("location")).toBeNull();
      expect(res.headers.getSetCookie()).toEqual([]);
      expect(res.headers.get("content-type")).toContain("application/json");
      expect(res.headers.get("x-request-id")).toBe(RAY);
      const text = await res.text();
      const body = JSON.parse(text) as Record<string, unknown>;
      expect(body.request_id).toBe(RAY);
      expect(text).not.toMatch(/ECONNREFUSED|private revocation bug/i);
      expect(text).not.toContain(token);
      expect(text).not.toContain(SESSION_SECRET);
      expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
    },
  );

  it("navigation gets the branded 503 page with the Support reference", async () => {
    const { store, cookie, token, bindings } = await logoutFixture();
    vi.spyOn(store, "revoke").mockRejectedValue(refused());
    const res = await post(cookie, "text/html", bindings);
    expect(res.status).toBe(503);
    expect(res.headers.get("location")).toBeNull();
    expect(res.headers.getSetCookie()).toEqual([]);
    expect(res.headers.get("content-type")).toContain("text/html");
    const html = await res.text();
    expect(html).toContain('data-testid="error-support-reference"');
    expect(html).toContain(RAY);
    expect(html).not.toMatch(/ECONNREFUSED/);
    expect(html).not.toContain(token);
  });

  it("the sign-out island keeps its generic failure copy for a refused logout (control)", async () => {
    const island = read("public/islands/auth-status.js");
    expect(island).toContain("logout-error");
    expect(island).toContain("Could not sign out. Please try again.");
  });
});

describe("moderator guide: copy the reference", () => {
  const incidents = (() => {
    const guide = read("docs/moderator-admin-guide.md");
    const start = guide.indexOf("## Moderator boundaries and incidents");
    const end = guide.indexOf("\n## ", start + 1);
    return guide.slice(start, end === -1 ? undefined : end);
  })();

  const row = (marker: string): string =>
    incidents.split("\n").find((line) => line.includes(marker)) ?? "";

  it("500 row tells moderators to copy the Support reference", () => {
    expect(row("(500)")).toMatch(/Support reference|request_id/);
  });

  it("503 row tells moderators to copy the Support reference", () => {
    expect(row("(503)")).toMatch(/Support reference|request_id/);
  });

  it("429 row tells moderators to copy the Support reference", () => {
    expect(row("(429)")).toMatch(/Support reference|request_id/);
  });

  it("member-incident checklist tells moderators to copy the reference", () => {
    const checklist = incidents.slice(incidents.indexOf("For a member incident"));
    expect(checklist.slice(0, 600)).toMatch(/Support reference|request_id/);
  });
});
