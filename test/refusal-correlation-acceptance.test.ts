const RAY = "0123456789abcdef-LHR";
const ULID = /^[0-7][0-9A-HJKMNP-TV-Z]{25}$/;
const APP_URL = "https://next.example.test";
const SESSION_SECRET = "test-session-secret-at-least-32-bytes-long";

/** The http.request correlation ids requestLog emitted on console.log. */
function loggedRequestIds(log: { mock: { calls: unknown[][] } }): string[] {
  const ids: string[] = [];
  for (const [line] of log.mock.calls) {
    try {
      const parsed = JSON.parse(String(line)) as { event?: string; request_id?: string };
      if (parsed.event === "http.request" && typeof parsed.request_id === "string")
        ids.push(parsed.request_id);
    } catch {
      // Other console.log output is not a request line.
    }
  }
  return ids;
}

/** Mount the real shared refusal helpers, with or without requestLog context. */
function harness(logged: boolean) {
  const inner = new Hono<{ Bindings: Env }>();
  inner.get("/deny", (c) => forbidden(c));
  inner.get("/deny.rss", (c) => forbidden(c));
  inner.get("/retired", (c) => gone(c));
  inner.get("/retired.rss", (c) => gone(c));
  inner.post("/upload", (c) => payloadTooLarge(c));
  inner.get("/throttled", (c) => rateLimitExceeded(c));
  if (!logged) return inner;
  const router = new Hono<{ Bindings: Env }>();
  router.use("*", requestLog);
  router.route("/", inner);
  return router;
}

const harnessEnv = { APP_URL } as Env;

beforeEach(() => {
  vi.spyOn(console, "log").mockImplementation(() => {});
  vi.spyOn(console, "warn").mockImplementation(() => {});
  vi.spyOn(console, "error").mockImplementation(() => {});
});
afterEach(() => vi.restoreAllMocks());

describe("refusal envelopes carry request_id", () => {
  it("403 JSON envelope adds request_id, additively", async () => {
    const res = await harness(true).request(
      "/deny",
      { headers: { accept: "application/json", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(403);
    expect(res.headers.get("x-request-id")).toBe(RAY);
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toMatchObject({ error: "forbidden" });
    expect(Object.keys(body).sort()).toEqual(["error", "message", "request_id"]);
    expect(body.request_id).toBe(RAY);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });

  it("410 JSON envelope adds request_id, additively", async () => {
    const res = await harness(true).request(
      "/retired",
      { headers: { accept: "application/json", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(410);
    expect(res.headers.get("x-request-id")).toBe(RAY);
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toMatchObject({ reason: "gone" });
    expect(Object.keys(body).sort()).toEqual(["message", "reason", "request_id"]);
    expect(body.request_id).toBe(RAY);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });

  it("413 JSON envelope adds request_id, additively", async () => {
    const res = await harness(true).request(
      "/upload",
      { method: "POST", headers: { accept: "application/json", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(413);
    expect(res.headers.get("x-request-id")).toBe(RAY);
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toMatchObject({ reason: "payload_too_large" });
    expect(Object.keys(body).sort()).toEqual(["message", "reason", "request_id"]);
    expect(body.request_id).toBe(RAY);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(RAY);
  });

  it("403 envelope uses the generated id when no Ray id is sent", async () => {
    const res = await harness(true).request(
      "/deny",
      { headers: { accept: "application/json" } },
      harnessEnv,
    );
    expect(res.status).toBe(403);
    const generated = res.headers.get("x-request-id");
    expect(generated).toMatch(ULID);
    expect(((await res.json()) as { request_id?: string }).request_id).toBe(generated);
    expect(loggedRequestIds(vi.mocked(console.log))).toContain(generated);
  });

  it("403 envelope omits request_id without requestLog context (control)", async () => {
    const res = await harness(false).request(
      "/deny",
      { headers: { accept: "application/json", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(403);
    expect(res.headers.get("x-request-id")).toBeNull();
    const body = (await res.json()) as Record<string, unknown>;
    expect(body).toEqual({
      error: "forbidden",
      message: "You do not have access to this.",
    });
    expect("request_id" in body).toBe(false);
  });

  it("429 envelope keeps its correlated shape (control)", async () => {
    const res = await harness(true).request(
      "/throttled",
      { headers: { accept: "application/json", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(429);
    expect(await res.json()).toEqual({
      reason: "rate_limited",
      message: "Too many requests. Try again in 60 seconds.",
      retry_after: 60,
      request_id: RAY,
    });
  });

  it("feed 403 stays bare text with no correlation field (control)", async () => {
    const res = await harness(true).request(
      "/deny.rss",
      { headers: { accept: "text/html", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(403);
    expect(res.headers.get("content-type")).toContain("text/plain");
    expect(await res.text()).toBe("Forbidden");
  });

  it("feed 410 stays bare text with no correlation field (control)", async () => {
    const res = await harness(true).request(
      "/retired.rss",
      { headers: { accept: "text/html", "cf-ray": RAY } },
      harnessEnv,
    );
    expect(res.status).toBe(410);
    expect(res.headers.get("content-type")).toContain("text/plain");
    expect(await res.text()).toBe("Gone");
  });
});

