const norm = (s: string): string => s.trim().toLowerCase();

// Full schedule fixture: upcoming + past + month-grid routing by SQL shape,
// the published-only distinct-games read, game WHERE filtering (so the
// follow-the-href proofs exercise the real facet), and zero RSVP answers.
function scheduleFixture(args: {
  upcoming?: EventRow[];
  monthRows?: EventRow[];
  past?: EventRow[];
  source?: DiscordEventsSource;
}) {
  const upcoming = args.upcoming ?? [];
  const monthRows = args.monthRows ?? [];
  const past = args.past ?? [];
  const source = args.source ?? discordSource();
  const queries: { sql: string; params: unknown[] }[] = [];
  const columns = Object.keys(getTableColumns(events)) as (keyof EventRow)[];
  const encode = (row: EventRow) =>
    columns.map((k) => {
      const v = row[k];
      return v instanceof Date ? v.toISOString() : v;
    });
  const applyFilters = (rows: EventRow[], sql: string, params: unknown[]): EventRow[] => {
    let out = rows;
    const qBound = params.find(
      (p): p is string => typeof p === "string" && p.startsWith("%") && p.endsWith("%"),
    );
    if (qBound) {
      const term = qBound.slice(1, -1).replace(/\\(.)/g, "$1").toLowerCase();
      out = out.filter(
        (r) =>
          r.title.toLowerCase().includes(term) ||
          (r.description ?? "").toLowerCase().includes(term),
      );
    }
    const wherePart = sql
      .split(/from "events"/i)
      .slice(1)
      .join(' from "events" ');
    if (/"game"/i.test(wherePart)) {
      const gameParam = params.find(
        (p): p is string =>
          typeof p === "string" &&
          !(p.startsWith("%") && p.endsWith("%")) &&
          !/^\d{4}-\d{2}-\d{2}[T ]/.test(p) &&
          !rows.some((row) => row.eventKey === p),
      );
      if (typeof gameParam === "string") {
        const want = norm(gameParam);
        out = out.filter((r) => r.game !== null && norm(r.game) === want);
      }
    }
    return out;
  };
  const db = drizzle(async (sql, params) => {
    queries.push({ sql, params: [...params] });
    if (sql.includes('from "rsvps"')) return { rows: [] };
    if (sql.startsWith('select "discord_event_id" from "events"')) return { rows: [] };
    if (/select\s+distinct/i.test(sql) && /game/i.test(sql)) {
      const games = [
        ...new Set(
          [...upcoming, ...monthRows, ...past]
            .filter((r) => r.status === "published" && r.game !== null && r.game.trim() !== "")
            .map((r) => r.game!.trim()),
        ),
      ].sort((a, b) => a.localeCompare(b));
      const hasLimit = sql.includes("limit");
      const limit = hasLimit ? Number(params.at(-1)) : games.length;
      const bounded = Number.isSafeInteger(limit) ? games.slice(0, Math.max(0, limit)) : games;
      return { rows: bounded.map((g) => [g]) };
    }
    if (sql.includes('"starts_at" < $')) {
      return { rows: applyFilters(monthRows, sql, params).map(encode) };
    }
    if (/"ends_at" </.test(sql)) {
      const rows = applyFilters(past, sql, params);
      if (/^select count/i.test(sql)) return { rows: [[rows.length]] };
      return { rows: rows.map(encode) };
    }
    let rows = applyFilters(upcoming, sql, params);
    if (sql.includes("!= 'draft'")) rows = rows.filter((row) => row.status !== "draft");
    if (/"event_key" = \$/.test(sql)) {
      rows = rows.filter((row) => params.includes(row.eventKey));
    }
    if (/^select count/i.test(sql)) return { rows: [[rows.length]] };
    if (sql.includes("limit")) {
      const hasOffset = sql.includes(" offset ");
      const offset = hasOffset ? Number(params.at(-1)) : 0;
      const limit = Number(params.at(hasOffset ? -2 : -1));
      const start = Number.isSafeInteger(offset) && offset > 0 ? offset : 0;
      const end = Number.isSafeInteger(limit) ? start + limit : rows.length;
      rows = rows.slice(start, end);
    }
    return { rows: rows.map(encode) };
  });
  Object.assign(db, {
    transaction: async (fn: (tx: Db) => Promise<void>) =>
      fn({ execute: async () => {} } as unknown as Db),
  });
  const adminDb = db as unknown as Db;
  const env = { ...baseEnv, ADMIN_DB: adminDb, DISCORD_EVENTS: source } as unknown as Env;
  return {
    db: adminDb,
    env,
    queries,
    source,
    request: (path: string, init?: RequestInit) => app.request(path, init, env),
  };
}

