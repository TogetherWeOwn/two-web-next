// Generate exact RFC 5892 joining contexts from the pinned Unicode UCD.
// Run: node ci/generate-joining-types.mjs [--check]
import { createHash } from "node:crypto";
import { readFileSync, writeFileSync } from "node:fs";

const fixture = new URL("../test/fixtures/unicode-17.0.0/DerivedJoiningType.txt", import.meta.url);
const destination = new URL("../src/admin/joining-types.ts", import.meta.url);
const data = readFileSync(fixture);
const sha = "f39ebe974825d6736aee15582250307aa532b2cfab3caf3f86bd23fddc9c5c4d";
if (createHash("sha256").update(data).digest("hex") !== sha) {
  throw new Error("Unicode 17.0.0 DerivedJoiningType fixture checksum mismatch");
}
const entries = [];
for (const line of data.toString("utf8").split("\n")) {
  const match = /^([0-9A-F]+)(?:\.\.([0-9A-F]+))?\s*;\s*([CDLRT])\s*#/.exec(line);
  if (!match) continue;
  entries.push({
    start: parseInt(match[1], 16),
    end: parseInt(match[2] ?? match[1], 16),
    type: match[3],
  });
}
const escape = (cp) =>
  cp <= 0xffff ? `\\u${cp.toString(16).padStart(4, "0")}` : `\\u{${cp.toString(16)}}`;
function characterClass(types) {
  const ranges = [];
  for (const { start, end } of entries
    .filter((entry) => types.includes(entry.type))
    .sort((a, b) => a.start - b.start)) {
    const previous = ranges.at(-1);
    if (previous && start === previous.end + 1) previous.end = end;
    else ranges.push({ start, end });
  }
  return ranges
    .map(({ start, end }) => (start === end ? escape(start) : `${escape(start)}-${escape(end)}`))
    .join("");
}
const output = [
  "// Generated by ci/generate-joining-types.mjs; do not hand edit.",
  "// Unicode 17.0.0: https://www.unicode.org/Public/17.0.0/ucd/extracted/DerivedJoiningType.txt",
  `// Source SHA-256: ${sha}`,
  "// Copyright Unicode, Inc. See test/fixtures/unicode-17.0.0/LICENSE.txt (Unicode License V3).",
  ...[
    ["JOINING_LEFT", "LD"],
    ["JOINING_RIGHT", "RD"],
    ["JOINING_TRANSPARENT", "T"],
  ].map(([name, types]) => `export const ${name} =\n  /[${characterClass(types)}]/u;`),
  "",
].join("\n");
if (process.argv.includes("--check")) {
  if (readFileSync(destination, "utf8") !== output) {
    throw new Error("Joining-type tables differ from the pinned Unicode data");
  }
} else {
  writeFileSync(destination, output);
}
