#!/usr/bin/env node
// Bundle the content-leaf stylesheets into a generated module so the Worker
// can inline them without a filesystem read: the staging Lighthouse audit
// measured mobile /rules LCP just over budget with render-blocking-resources
// savings of ~150 ms across styles.css, theme-tokens.css and theme.css,
// while the <link rel="preload"> hints for those same files measured zero
// effect (the whole head fits the first response chunk). Inlining removes
// all three render-blocking requests from the content leaves (/about, /faq,
// /rules, /privacy — the only theme="content" pages); the <style> block is
// allowlisted by its sha256 hash, so style-src keeps no 'unsafe-inline'.
// Regenerated by postinstall or node ci/build-leaf-css.mjs; the drift suite
// checks output coherence. CI reports base/head CSP hashes for source review.
// Keep font-fallback rationale here rather than shipping it in theme.css and
// again in the inlined block: Latin-only, Arial-metric fallback; arrows (U+2192)
// keep prior rendering. Overrides = Display's 93%/34.6% ascent/descent at 77% +
// margin: fallback hero paints >= swapped-in text (no larger repaint).
// Same rule for the Logo/Icon 1 brand ramp (ember #ff9c36 -> magenta #ff0e52 ->
// violet #5701ae, top to bottom): the three color tokens ship in
// public/theme-tokens.css with no comment and no gradient token, because this
// bundle inlines verbatim into the homepage critical CSS under a 24.8 kB
// ratchet (test/homepage-mobile-lcp-acceptance.test.ts). The tokens keep
// standard Biome formatting (lint gates outrank byte-shaving here); rationale
// lives here so shipped bytes stay minimal, and the gradient stops live baked
// in the logo, icon and favicon artwork. A component that needs the gradient
// re-adds the token with its own budget.
import { createHash, randomUUID } from "node:crypto";
import { closeSync, openSync, readFileSync, renameSync, rmSync, writeFileSync } from "node:fs";
import { dirname, join, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const repoRoot = resolve(dirname(fileURLToPath(import.meta.url)), "..");
const SOURCES = [
  "public/styles.css",
  "public/theme-tokens.css",
  "public/theme.css",
  "web/src/lib/site-header.css",
];
const OUT = "src/leaf-critical-css.ts";

export function build() {
  const css = SOURCES.map((entry) => readFileSync(join(repoRoot, entry), "utf8")).join("\n");
  if (/<\/style/i.test(css)) {
    throw new Error("refusing to inline CSS containing a closing style tag");
  }
  const sha256 = createHash("sha256").update(css, "utf8").digest("base64");
  const packed = !css.includes("~");
  const literal = JSON.stringify(packed ? css.replaceAll(".base-theme", "~") : css);
  const initializer = packed ? `${literal}.split("~").join(".base-theme")` : literal;
  const text =
    `// GENERATED from ${SOURCES.join(", ")} — do not hand-edit.\n` +
    `// Regen: node ci/build-leaf-css.mjs (drift is pinned by test/leaf-css-drift.test.ts).\n` +
    `export const LEAF_CRITICAL_CSS: string =\n  ${initializer};\n` +
    `export const LEAF_CRITICAL_CSS_SHA256: string = ${JSON.stringify(sha256)};\n`;
  return { text, sha256 };
}

const { text, sha256 } = build();
const output = join(repoRoot, OUT);
const temporary = `${output}.${randomUUID()}.tmp`;
let fd = openSync(temporary, "wx");
try {
  writeFileSync(fd, text);
  closeSync(fd);
  fd = undefined;
  renameSync(temporary, output);
} finally {
  if (fd !== undefined) closeSync(fd);
  rmSync(temporary, { force: true });
}
console.log(`${OUT}: ${text.length} chars, sha256 ${sha256}`);
